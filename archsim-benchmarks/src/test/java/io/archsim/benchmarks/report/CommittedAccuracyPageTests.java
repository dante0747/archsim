package io.archsim.benchmarks.report;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.Map;

import org.junit.jupiter.api.Test;
import tools.jackson.databind.JsonNode;

import io.archsim.benchmarks.RepositoryLayout;
import io.archsim.benchmarks.docker.Cpusets;
import io.archsim.benchmarks.experiments.Engines;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * {@code accuracy.json}'s data, from the committed results, and
 * {@code docs/validation.md} say the same: each experiment's knee and p95 row, its
 * low-load rows, its environment and its tier, and every kept run's knee. Each file is
 * also regenerated byte for byte ({@code ReportParityTests}); this keeps them together
 * once both are written again.
 */
class CommittedAccuracyPageTests {

	private static final RepositoryLayout LAYOUT = RepositoryLayout.current();

	private static final JsonNode DATA = AccuracyData
		.of(new ReportSources(LAYOUT.results(), Engines.read(LAYOUT.engines()), Cpusets.declaredIn(LAYOUT.compose())))
		.orElseThrow();

	private static final String PAGE = readPage();

	/** The sample label as the page's tables show it. */
	private static final Map<String, String> SAMPLES = Map.of("held-out", "held out", "tuned-on", "tuned on");

	@Test
	void experiments_eachOnesKneeAndP95Row_isOnThePage() {
		assertThat(DATA.get("experiments").valueStream()).allSatisfy((experiment) -> {
			String id = experiment.get("id").stringValue();
			JsonNode knee = experiment.at("/knee/text");
			JsonNode below = experiment.get("p95BelowKnee");
			assertThat(PAGE)
				.contains("| [" + id + "](#" + id + ") | " + SAMPLES.get(experiment.get("sample").stringValue()) + " | "
						+ text(knee, "measured") + " req/s | " + text(knee, "predicted") + " req/s | "
						+ text(knee, "error") + " | " + text(below.get("text"), "medianAbsError") + " / "
						+ text(below.get("text"), "maxAbsError") + " (" + below.get("steps").intValue() + " steps) |");
		});
	}

	@Test
	void experiments_eachOnesLowLoadRows_areOnThePage() {
		assertThat(DATA.get("experiments").valueStream()).allSatisfy((experiment) -> {
			String id = experiment.get("id").stringValue();
			experiment.get("lowLoad").forEach((low) -> {
				JsonNode text = low.get("text");
				assertThat(PAGE)
					.contains("| " + id + " | " + text(text, "offered") + " (" + text(text, "fraction") + " the ")
					.contains(text(text, "diff") + " (" + text(text, "p95Error") + ") |");
			});
		});
	}

	@Test
	void experiments_eachOnesEnvironmentAndTier_areOnThePage() {
		assertThat(DATA.get("experiments").valueStream()).allSatisfy((experiment) -> {
			String id = experiment.get("id").stringValue();
			String tier = "validated".equals(experiment.get("tier").stringValue()) ? "yes" : "no";
			assertThat(PAGE).contains(experiment.at("/environment/text").stringValue());
			assertThat(PAGE.lines())
				.anyMatch((line) -> line.startsWith("| " + id + " |") && line.endsWith("| " + tier + " |"));
		});
	}

	@Test
	void history_everyKeptRunsKnee_isOnThePage() {
		assertThat(DATA.get("history").valueStream().flatMap(JsonNode::valueStream)).allSatisfy((run) -> {
			JsonNode text = run.get("text");
			assertThat(PAGE).contains("| " + text(text, "measuredKnee") + " req/s | " + text(text, "predictedKnee")
					+ " req/s | " + text(text, "kneeError") + " |");
		});
	}

	// the headline's table of the held-out runs against the simple estimates is written
	// by hand, so a new campaign's figures must reach it too
	@Test
	void againstEstimatesHeldOut_eachMedian_isInTheHeadlinesTable() {
		JsonNode against = DATA.at("/summary/againstEstimatesHeldOut");

		assertThat(PAGE)
			.contains("| **ArchSim's simulator** | " + text(against.at("/simulator/text"), "medianAbsError") + " |");
		assertThat(against.get("estimates").valueStream()).allSatisfy((estimate) -> assertThat(PAGE)
			.contains("| " + text(estimate, "name") + " | " + text(estimate.get("text"), "medianAbsError") + " |"));
	}

	private static String text(JsonNode texts, String key) {
		return texts.get(key).stringValue();
	}

	private static String readPage() {
		try {
			return Files.readString(LAYOUT.validationPage(), StandardCharsets.UTF_8);
		}
		catch (IOException ex) {
			throw new UncheckedIOException(ex);
		}
	}

}
