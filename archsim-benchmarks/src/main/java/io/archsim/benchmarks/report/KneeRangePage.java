package io.archsim.benchmarks.report;

import java.util.ArrayList;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

import tools.jackson.databind.JsonNode;

import io.archsim.benchmarks.values.PythonStatistics;
import io.archsim.benchmarks.values.PythonValues;
import io.archsim.model.text.PythonFormat;
import io.archsim.model.text.PythonText;

/**
 * {@code docs/validation/knee-range.md}: the predicted range's fit
 * ({@code benchmarks/knee-range.json}) and its check, in-sample and leaving out each run
 * and each experiment.
 */
final class KneeRangePage {

	private static final List<String> HEAD = List.of("# The knee's predicted range: fit and check (in-sample)", "",
			"Generated by `./gradlew :archsim-benchmarks:run --args=\"report --dev\"` from "
					+ "`benchmarks/knee-range.json`, which `uv run python benchmarks/run.py range-fit` "
					+ "writes. The range is built as docs/validation.md describes "
					+ "([Protocol](../validation.md#protocol), step 3). Its check here uses only the four in-sample "
					+ "experiments, with today's harness and engine "
					+ "re-deriving each run's inputs and knee from its calibration (as the [development "
					+ "checks](dev-checks.md) do): the knees are not the predictions the runs made before measuring, "
					+ "and the model was tuned on these runs. The held-out experiments test the range out of sample.",
			"");

	/** The folds the fit is checked in, by their names in the fit and on the page. */
	private static final Map<String, String> FOLDS = folds();

	private static final int COMMIT_LENGTH = 12;

	private static final int RUN_COLUMNS = 6;

	private KneeRangePage() {
	}

	private static Map<String, String> folds() {
		Map<String, String> folds = new LinkedHashMap<>();
		folds.put("inSample", "In-sample");
		folds.put("leaveRunOut", "Leaving out the run");
		folds.put("leaveExperimentOut", "Leaving out its experiment");
		return folds;
	}

	/**
	 * The page's text.
	 * @param fit {@code knee-range.json}, or None
	 * @return the page, ending with a newline
	 */
	static String text(JsonNode fit) {
		List<String> lines = new ArrayList<>(HEAD);
		if (!PythonText.truthy(fit)) {
			lines.add("_No fit yet._");
			lines.add("");
			return String.join("\n", lines);
		}
		lines.addAll(coverage(fit));
		lines.addAll(inputs(fit));
		lines.addAll(model(fit));
		lines.addAll(runs(fit));
		lines.add("");
		return String.join("\n", lines);
	}

	private static List<String> coverage(JsonNode fit) {
		JsonNode counts = fit.at("/check/counts");
		JsonNode before = fit.at("/check/before");
		String commit = PythonText.str(PythonValues.get(fit, "commit"));
		List<String> lines = new ArrayList<>(List.of(
				"Fitted " + PythonText.str(fit.get("at")) + " with engine " + PythonText.str(fit.get("engineVersion"))
						+ " (commit `" + commit.substring(0, Math.min(commit.length(), COMMIT_LENGTH)) + "`), on "
						+ fit.get("calibrations").size() + " calibrations and " + PythonText.str(fit.get("runs"))
						+ " counted runs of " + PythonText.str(fit.get("experiments")) + " experiments.",
				"", "## Coverage", "",
				"How many of the runs' measured knees fell inside the range, at three nominal coverages:", "",
				"| Nominal coverage | " + String.join(" | ", FOLDS.values()) + " |",
				"| --- ".repeat(1 + FOLDS.size()) + "|"));
		lines.addAll(levels(counts));
		lines.addAll(List.of("", "Before W28 the same runs' ranges (their replicate calibration sets' knees, nominal "
				+ Figures.magnitude(PythonValues.get(before, "nominalCoverage")) + ") held "
				+ PythonText.str(before.get("inRange")) + " of " + PythonText.str(before.get("withRange")) + ".", ""));
		fit.at("/check/folds")
			.properties()
			.forEach((fold) -> lines
				.add("- " + FOLDS.get(fold.getKey()) + ": " + PythonText.str(fold.getValue()) + "."));
		return lines;
	}

	// the runs inside the range at each nominal coverage, in each fold
	private static List<String> levels(JsonNode counts) {
		List<String> levels = new ArrayList<>(counts.get("inSample").propertyNames());
		levels.sort(Comparator.comparingDouble(Double::parseDouble));
		List<String> lines = new ArrayList<>();
		for (String level : levels) {
			List<String> cells = FOLDS.keySet()
				.stream()
				.map((fold) -> PythonText.str(counts.get(fold).get(level).get(0)) + " of "
						+ PythonText.str(counts.get(fold).get(level).get(1)))
				.toList();
			lines.add("| " + PythonFormat.format(Double.parseDouble(level), ".0%") + " | " + String.join(" | ", cells)
					+ " |");
		}
		return lines;
	}

	private static List<String> inputs(JsonNode fit) {
		List<String> lines = new ArrayList<>(List.of("", "## Each input's run-to-run variation", "",
				"Between calibrations of the same experiment, pooled over the experiments; the band is one standard "
						+ "deviation.",
				"", "| Input | Log standard deviation | One standard deviation | Calibrations | Experiments |",
				"| --- | --- | --- | --- | --- |"));
		fit.get("inputs").properties().forEach((input) -> {
			JsonNode variation = input.getValue();
			lines.add("| `" + input.getKey() + "` | " + Figures.format(variation.get("sigma"), ".3f") + " | "
					+ plusMinus(variation.get("sigma"), 1.0) + " | " + PythonText.str(variation.get("calibrations"))
					+ " | " + PythonText.str(variation.get("experiments")) + " |");
		});
		lines.addAll(List.of("",
				"An input never seen varying takes the median, " + Figures.format(fit.get("fallbackSigma"), ".3f")
						+ ". Common correlation between two inputs of the same calibration: "
						+ Figures.format(fit.get("correlation"), ".2f") + "."));
		return lines;
	}

	private static List<String> model(JsonNode fit) {
		JsonNode sigma = fit.at("/model/sigma");
		double coverage = fit.get("nominalCoverage").doubleValue();
		double deviations = PythonStatistics.normalInverse((1 + coverage) / 2);
		return List.of("", "## The model's own error", "", "Log standard deviation " + Figures.format(sigma, ".3f")
				+ " (" + plusMinus(sigma, 1.0) + " for one standard deviation, " + plusMinus(sigma, deviations)
				+ " for the " + PythonFormat.format(coverage, ".0%") + " range alone), by maximum likelihood over "
				+ PythonText.str(fit.at("/model/runs")) + " runs of " + PythonText.str(fit.at("/model/experiments"))
				+ " experiments after each run's calibration spread.");
	}

	private static List<String> runs(JsonNode fit) {
		List<String> lines = new ArrayList<>(List.of("", "## Each run", "",
				"Knees in req/s; error = ln(measured / predicted); the ranges are the "
						+ PythonFormat.format(fit.get("nominalCoverage").doubleValue(), ".0%")
						+ " ones, inside (yes) or not (no).",
				"",
				"| Experiment | Results | Knee measured | Knee predicted | Error | Calibration spread | "
						+ String.join(" | ", FOLDS.values()) + " |",
				"| --- ".repeat(RUN_COLUMNS + FOLDS.size()) + "|"));
		for (JsonNode run : fit.get("checked")) {
			List<String> cells = FOLDS.keySet()
				.stream()
				.map((fold) -> rangeCell(PythonValues.get(run.get("ranges"), fold)))
				.toList();
			lines.add("| " + run.get("experiment").stringValue() + " | `" + run.get("source").stringValue() + "/` | "
					+ Figures.knee(run.get("measuredKnee")) + " | " + Figures.rate(run.get("knee")) + " | "
					+ Figures.format(run.get("error"), "+.3f") + " | "
					+ Figures.format(run.get("calibrationSigma"), ".3f") + " | " + String.join(" | ", cells) + " |");
		}
		return lines;
	}

	private static String rangeCell(JsonNode range) {
		if (!PythonText.truthy(range)) {
			return Figures.NONE;
		}
		return Figures.rate(PythonValues.get(range, "lowRps")) + " to "
				+ Figures.rate(PythonValues.get(range, "highRps")) + " ("
				+ (PythonText.truthy(PythonValues.get(range, "holds")) ? "yes" : "no") + ")";
	}

	/**
	 * A log standard deviation as the multiplicative band it means: 0.10 is
	 * {@code x0.90 to x1.11}.
	 * @param sigma the log standard deviation, or None
	 * @param deviations how many standard deviations the band spans each way
	 * @return the band
	 */
	static String plusMinus(JsonNode sigma, double deviations) {
		if (PythonValues.isNone(sigma)) {
			return Figures.NONE;
		}
		return "x" + PythonFormat.format(StrictMath.exp(-deviations * sigma.doubleValue()), ".2f") + " to x"
				+ PythonFormat.format(StrictMath.exp(deviations * sigma.doubleValue()), ".2f");
	}

}
