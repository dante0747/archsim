package io.archsim.benchmarks.report;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Collections;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Objects;
import java.util.Optional;
import java.util.TreeMap;
import java.util.TreeSet;
import java.util.stream.Stream;

import tools.jackson.databind.JsonNode;

import io.archsim.benchmarks.experiments.Experiment;
import io.archsim.benchmarks.results.ResultFiles;
import io.archsim.benchmarks.values.PythonValues;
import io.archsim.model.text.PythonText;

/**
 * {@code docs/validation/dev-checks.md}: each kept run's knee, measured and simulated by
 * each engine version checked ({@code resimulate}'s development checks under
 * {@code results/dev/}), and the median error per engine. In-sample: never on the
 * validation page or {@code /accuracy} but for one sentence.
 */
final class DevChecksPage {

	private static final List<String> HEAD = List.of("# Development checks (in-sample)", "",
			"Generated by `./gradlew :archsim-benchmarks:run --args=\"report --dev\"` from `benchmarks/results/dev/`, "
					+ "which `./gradlew :archsim-benchmarks:run --args=\"resimulate\"` writes. Each row is a kept "
					+ "benchmark run: its calibration passes are turned into model inputs again with today's harness, "
					+ "and its measured load steps are simulated with the engine in each column. These checks are "
					+ "designed after the measurements were seen, so they show what a model change does on data it "
					+ "may have been tuned on. They are never predictions: docs/validation.md and the /accuracy page "
					+ "show only one sentence from them, labelled re-simulated, on how many of the frozen engine's "
					+ "knees the Java engine reproduces.",
			"");

	/** A check's depth under {@code results/dev/}: its label, experiment and file. */
	private static final int CHECK_DEPTH = 3;

	private DevChecksPage() {
	}

	/**
	 * The page's text.
	 * @param results the results folder
	 * @return the page, ending with a newline
	 */
	static String text(Path results) {
		Map<String, Map<String, Map<String, JsonNode>>> checks = checks(results);
		List<String> lines = new ArrayList<>(HEAD);
		if (checks.isEmpty()) {
			lines.add("_No development checks yet._");
			lines.add("");
			return String.join("\n", lines);
		}
		List<String> engines = new ArrayList<>(checks.keySet());
		engines.sort(Comparator.comparing(DevChecksPage::versionKey, DevChecksPage::compareVersions));
		Map<String, String> hosts = new LinkedHashMap<>();
		engines.forEach((engine) -> hosts.put(engine, host(checks.getOrDefault(engine, Map.of())).orElse("")));
		DevChecksTable table = new DevChecksTable(checks, engines);
		lines.add(table.head(hosts));
		lines.add("| --- ".repeat(DevChecksTable.FIXED_COLUMNS + engines.size()) + "|");
		lines.addAll(table.rows());
		lines.addAll(table.notes(hosts));
		return String.join("\n", lines);
	}

	/**
	 * Every development check under {@code results/dev/}: engine version, then
	 * experiment, then calibration time.
	 * @param results the results folder
	 * @return the checks
	 */
	static Map<String, Map<String, Map<String, JsonNode>>> checks(Path results) {
		Map<String, Map<String, Map<String, JsonNode>>> checks = new LinkedHashMap<>();
		for (Path file : files(results.resolve("dev"))) {
			JsonNode check = ResultFiles.read(file).orElseThrow();
			JsonNode at = PythonValues.get(check, "calibratedAt");
			String name = file.getFileName().toString();
			checks.computeIfAbsent(check.get("engineVersion").stringValue(), (engine) -> new LinkedHashMap<>())
				.computeIfAbsent(check.get("experiment").stringValue(), (experiment) -> new TreeMap<>())
				.put(PythonText.truthy(at) ? at.stringValue() : name.substring(0, name.length() - ".json".length()),
						check);
		}
		return checks;
	}

	// results/dev/<label>/<experiment>/<check>.json, in the order of their paths' parts
	private static List<Path> files(Path dev) {
		if (!Files.isDirectory(dev)) {
			return List.of();
		}
		try (Stream<Path> files = Files.walk(dev, CHECK_DEPTH)) {
			return files.filter((file) -> dev.relativize(file).getNameCount() == CHECK_DEPTH)
				.filter((file) -> file.getFileName().toString().endsWith(".json"))
				.sorted(Comparator.comparing((Path file) -> parts(dev.relativize(file)), DevChecksPage::compareParts))
				.toList();
		}
		catch (IOException ex) {
			throw new UncheckedIOException(ex);
		}
	}

	private static List<String> parts(Path relative) {
		List<String> parts = new ArrayList<>();
		relative.forEach((part) -> parts.add(part.toString()));
		return parts;
	}

	private static int compareParts(List<String> left, List<String> right) {
		for (int i = 0; i < Math.min(left.size(), right.size()); i++) {
			int order = left.get(i).compareTo(right.get(i));
			if (order != 0) {
				return order;
			}
		}
		return Integer.compare(left.size(), right.size());
	}

	// an engine checked with the designs on a host machine: where its machine came from
	private static Optional<String> host(Map<String, Map<String, JsonNode>> byExperiment) {
		return byExperiment.values()
			.stream()
			.flatMap((runs) -> runs.values().stream())
			.filter((check) -> check.path("inputs").has("host"))
			.map((check) -> check.at("/inputs/host/how").stringValue())
			.findFirst();
	}

	// "0.15.0-w21" is (0, 15): only the parts that are all digits count
	private static List<Integer> versionKey(String version) {
		List<Integer> key = new ArrayList<>();
		for (String part : version.split("\\.", -1)) {
			if (!part.isEmpty() && part.chars().allMatch(Character::isDigit)) {
				key.add(Integer.parseInt(part));
			}
		}
		return key;
	}

	private static int compareVersions(List<Integer> left, List<Integer> right) {
		for (int i = 0; i < Math.min(left.size(), right.size()); i++) {
			int order = Integer.compare(left.get(i), right.get(i));
			if (order != 0) {
				return order;
			}
		}
		return Integer.compare(left.size(), right.size());
	}

	/**
	 * The page's table: a row per kept run that any engine checked, a column per engine,
	 * from the checks by engine, experiment and calibration time, and the engines in
	 * version order.
	 */
	private static final class DevChecksTable {

		static final int FIXED_COLUMNS = 6;

		private final Map<String, Map<String, Map<String, JsonNode>>> checks;

		private final List<String> engines;

		DevChecksTable(Map<String, Map<String, Map<String, JsonNode>>> checks, List<String> engines) {
			this.checks = checks;
			this.engines = List.copyOf(engines);
		}

		String head(Map<String, String> hosts) {
			List<String> columns = this.engines.stream()
				.map((engine) -> "Engine " + engine
						+ (hosts.getOrDefault(engine, "").isEmpty() ? "" : " with its host machine") + ": knee (error)")
				.toList();
			return "| Experiment | Results | Calibrated (UTC) | Inputs as calibrated | Knee measured | Counted | "
					+ String.join(" | ", columns) + " |";
		}

		List<String> rows() {
			List<String> rows = new ArrayList<>();
			for (Experiment experiment : LatestRuns.inPageOrder()) {
				TreeSet<String> times = new TreeSet<>();
				this.engines.forEach((engine) -> times.addAll(runs(engine, experiment.id()).keySet()));
				times.forEach((at) -> rows.add(row(experiment.id(), at)));
			}
			return rows;
		}

		private String row(String experiment, String at) {
			JsonNode any = anyCheck(experiment, at);
			JsonNode comparison = any.get("comparison");
			boolean disturbed = disturbed(experiment, at);
			List<String> cells = this.engines.stream().map((engine) -> cell(engine, experiment, at)).toList();
			return "| " + experiment + " | `" + any.get("results").stringValue() + "/` | " + at + " | "
					+ (any.get("inputsAsCalibrated").booleanValue() ? "yes" : "no") + " | "
					+ Figures.knee(comparison.get("measuredKnee")) + " | " + (disturbed ? "no: disturbed" : "yes")
					+ " | " + String.join(" | ", cells) + " |";
		}

		private String cell(String engine, String experiment, String at) {
			JsonNode check = runs(engine, experiment).get(at);
			if (check == null) {
				return Figures.NONE;
			}
			JsonNode comparison = check.get("comparison");
			return Figures.knee(comparison.get("predictedKnee")) + " (" + Figures.percent(comparison.get("kneeError"))
					+ ")";
		}

		List<String> notes(Map<String, String> hosts) {
			List<String> notes = new ArrayList<>(
					List.of("", "Knees in req/s; error = (simulated - measured) / measured.", ""));
			this.engines.forEach((engine) -> notes.add(summary(engine)));
			List<String> machines = new ArrayList<>();
			hosts.forEach((engine, how) -> {
				if (!how.isEmpty()) {
					machines.add("- Engine " + engine + " ran the designs on a host machine (`BENCH_HOST=on`, `run.py "
							+ "machine_inputs`): " + how + ".");
				}
			});
			if (!machines.isEmpty()) {
				notes.add("");
				notes.addAll(machines);
			}
			notes.addAll(List.of("", "\"Inputs as calibrated: no\" marks a run whose protocol derived its inputs "
					+ "differently from today's code (v2 had no anchoring of the client latency), so its row is "
					+ "today's reading of the same passes. Runs calibrated from one pass (run 1) are left out. A "
					+ "disturbed run missed the objective at one load step and met it at a higher one "
					+ "(docs/validation.md, protocol step 5): it is listed, but left out of the medians.", ""));
			return notes;
		}

		// the median absolute knee error over the latest run it checked of each
		// experiment and over every counted run, leaving disturbed runs out
		private String summary(String engine) {
			List<JsonNode> latest = new ArrayList<>();
			List<JsonNode> all = new ArrayList<>();
			for (Experiment experiment : LatestRuns.inPageOrder()) {
				Map<String, JsonNode> runs = runs(engine, experiment.id());
				runs.forEach((at, check) -> counted(experiment.id(), at, check).ifPresent((error) -> {
					all.add(error);
					if (at.equals(Collections.max(runs.keySet()))) {
						latest.add(error);
					}
				}));
			}
			return "- Engine " + engine + ": median absolute knee error "
					+ Figures.magnitude(PythonValues.median(latest)) + " over the latest run it checked of each "
					+ "experiment, " + Figures.magnitude(PythonValues.median(all)) + " over all " + all.size()
					+ " counted runs.";
		}

		// a check's absolute knee error, unless it has none or its run was disturbed
		private Optional<JsonNode> counted(String experiment, String at, JsonNode check) {
			JsonNode error = check.get("comparison").get("kneeError");
			if (PythonValues.isNone(error) || disturbed(experiment, at)) {
				return Optional.empty();
			}
			return Optional.of(PythonValues.abs(error));
		}

		// the first engine's check of a run
		private JsonNode anyCheck(String experiment, String at) {
			return this.engines.stream()
				.map((engine) -> runs(engine, experiment).get(at))
				.filter(Objects::nonNull)
				.findFirst()
				.orElseThrow();
		}

		// the measured ladder is the run's own: a disturbed run measures no engine
		private boolean disturbed(String experiment, String at) {
			JsonNode rows = anyCheck(experiment, at).get("comparison").get("rows");
			return !RunHistory.disturbed(rows.valueStream().toList()).isEmpty();
		}

		private Map<String, JsonNode> runs(String engine, String experiment) {
			return this.checks.getOrDefault(engine, Map.of()).getOrDefault(experiment, new TreeMap<>());
		}

	}

}
