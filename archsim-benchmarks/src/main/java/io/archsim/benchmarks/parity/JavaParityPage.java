package io.archsim.benchmarks.parity;

import java.util.ArrayList;
import java.util.List;

import tools.jackson.databind.JsonNode;
import tools.jackson.databind.node.ObjectNode;

import io.archsim.benchmarks.results.KneePairs;
import io.archsim.benchmarks.values.PythonValues;

/**
 * {@code docs/validation/java-parity.md}, stage 4's parity report: the Java simulator
 * against the frozen engine 0.16.0, by the port plan's bar. Every template case, 20 seeds
 * each: Java's median p50, p95, throughput and each part's utilization inside Python's
 * seed range and within 2% of its median, from {@code simulation-parity.json}. Every kept
 * calibration: the re-simulated knee within 2% of the frozen engine's. And each
 * template's speed on both engines, which is not part of the bar.
 */
final class JavaParityPage {

	/** How many times each engine ran each template for the speed comparison. */
	static final int REPEATS = 5;

	/** Writes {@code simulation-parity.json} from the baselines. */
	static final String PARITY_COMMAND = "./gradlew :archsim-engine:parity -Parchsim.parity.out=docs/validation";

	/**
	 * Wrote the frozen engine's speed; the script went with the engine at stage 5's exit.
	 */
	static final String PYTHON_SPEED_COMMAND = "uv run python scripts/perf.py --label python-" + KneePairs.FROZEN_ENGINE
			+ " --repeats " + REPEATS;

	/** Writes the Java engine's speed. */
	static final String JAVA_SPEED_COMMAND = "./gradlew :archsim-engine:speed -Parchsim.speed.out="
			+ JavaParity.JAVA_SPEED + " -Parchsim.speed.repeats=" + REPEATS;

	/** Writes this page. */
	static final String COMMAND = "./gradlew :archsim-benchmarks:run --args=\"java-parity\"";

	/** Wrote the frozen engine's knees while it was the harness's engine. */
	private static final String PYTHON_KNEES_COMMAND = "uv run python benchmarks/run.py resimulate --label "
			+ KneePairs.PYTHON_KNEES;

	/** Wrote the Java engine's knees before it had a version of its own. */
	private static final String JAVA_KNEES_COMMAND = "BENCH_ENGINE=java uv run python benchmarks/run.py resimulate";

	private JavaParityPage() {
	}

	/**
	 * The page.
	 * @param parity {@code simulation-parity.json}
	 * @param knees the kept calibrations' knees on both engines ({@link KneePairs})
	 * @param speed each template's speed on both engines, or not measured yet
	 * @return the page's text
	 */
	static String render(JsonNode parity, List<ObjectNode> knees, Speed speed) {
		List<String> lines = new ArrayList<>(List.of("# Java parity: the simulator against the frozen engine", "",
				headline(parity, knees), "",
				"Generated by `" + COMMAND + "`. The formal criterion, stage 4's bar "
						+ "([the port plan](../proposals/java-25-port.md)): for every template case, with 20 seeds "
						+ "each, the Java simulator's median p50, p95, throughput and each part's utilization fall "
						+ "inside the frozen engine 0.16.0's seed range and within 2% of its median; every kept "
						+ "calibration's re-simulated knee is within 2% of the frozen engine's.",
				""));
		lines.addAll(summary(parity));
		lines.addAll(List.of("", "## Cases that miss the bar", ""));
		lines.addAll(ParityTables.misses(parity.get("results")));
		lines.addAll(List.of("", "## Kept calibrations' knees", ""));
		lines.addAll(ParityTables.knees(knees));
		lines.addAll(List.of("", "## Speed", ""));
		lines.addAll(speed.lines());
		lines.addAll(List.of("", "## Each case", ""));
		lines.addAll(ParityTables.cases(parity.get("results")));
		lines.addAll(List.of("", "## How it was measured", ""));
		lines.addAll(method(parity, speed));
		lines.add("");
		return String.join("\n", lines);
	}

	private static String headline(JsonNode parity, List<ObjectNode> knees) {
		long runs = parity.get("runs").longValue();
		long cases = parity.get("cases").longValue();
		long exact = parity.get("exactReplays").longValue();
		long meeting = parity.get("casesMeetingTheBar").longValue();
		long within = ParityTables.count(knees, "withinTwoPercent");
		boolean barMet = meeting == cases && !knees.isEmpty() && within == knees.size();
		boolean replayed = exact == runs && parity.get("digestsEqual").longValue() == runs;
		if (barMet && replayed && knees.stream().allMatch(KneePairs::sameKnee)) {
			return "**Every case, run and kept knee matches the frozen engine exactly.** All "
					+ ParityNumbers.count(runs) + " runs of the " + cases + " template cases replay it figure for "
					+ "figure and digest for digest, and all " + knees.size() + " kept calibrations' knees are its "
					+ "knees.";
		}
		return "**Stage 4's bar is " + (barMet ? "met" : "not met") + ".** " + meeting + " of " + cases
				+ " template cases and " + within + " of " + knees.size() + " kept knees meet it; "
				+ ParityNumbers.count(exact) + " of " + ParityNumbers.count(runs)
				+ " runs replay the frozen engine exactly.";
	}

	private static List<String> summary(JsonNode parity) {
		List<String> lines = new ArrayList<>(counts(parity));
		lines.addAll(ParityDepartures.notReplayed(parity));
		lines.add(worst(PythonValues.get(parity, "worst")));
		return lines;
	}

	private static List<String> counts(JsonNode parity) {
		long cases = parity.get("cases").longValue();
		return List.of("- **" + parity.get("casesMeetingTheBar").longValue() + " of " + cases
				+ "** template cases meet the bar: " + parity.get("casesInsideTheRange").longValue() + " of " + cases
				+ " inside Python's seed range, " + parity.get("casesWithinTwoPercent").longValue() + " of " + cases
				+ " within 2% of its median; " + parity.get("casesWithMismatchedFailures").longValue()
				+ " with a seed failing otherwise than Python's (runs failed: Python "
				+ parity.get("pythonRunsFailed").longValue() + ", Java " + parity.get("javaRunsFailed").longValue()
				+ ").",
				"- **" + ParityNumbers.count(parity.get("exactReplays").longValue()) + " of "
						+ ParityNumbers.count(parity.get("runs").longValue())
						+ "** runs replay the frozen engine's exactly, every figure kept, read as its where the "
						+ "engine has changed on purpose since (below); "
						+ ParityNumbers.count(parity.get("digestsEqual").longValue()) + " give its result digest, and "
						+ parity.get("casesReplayingExactly").longValue() + " of " + cases
						+ " cases replay in every seed.");
	}

	private static String worst(JsonNode worst) {
		if (PythonValues.isNone(worst)) {
			return "- No metric was measured in any case.";
		}
		JsonNode metric = worst.get("verdict");
		JsonNode distance = metric.get("distance");
		if (!PythonValues.isNone(distance) && distance.doubleValue() == 0) {
			return "- No metric is off: every Java median is Python's.";
		}
		String off = PythonValues.isNone(distance) ? ParityNumbers.NOT_MEASURED
				: ParityNumbers.percent(distance) + " off";
		return "- The metric furthest from Python's: " + worst.get("template").stringValue() + " `"
				+ worst.get("scenario").stringValue() + "`, " + metric.get("metric").stringValue() + ": Java's median "
				+ ParityTables.javaMedian(metric) + " against Python's "
				+ ParityNumbers.number(metric.get("pythonMedian")) + " (" + ParityTables.pythonRange(metric) + "), "
				+ off + ".";
	}

	private static List<String> method(JsonNode parity, Speed speed) {
		List<String> lines = new ArrayList<>(List.of(
				"- The baselines: `scripts/export_simulation_baselines.py` simulated every template case in full on "
						+ "the frozen engine, with the workload's seed and the 19 after it "
						+ "([ADR-0052](../adr/0052-record-the-frozen-engines-simulation-baselines-once.md)).",
				"- The Java runs: `" + PARITY_COMMAND + "` simulated the same runs (" + parity.get("threads").asString()
						+ " at a time) and wrote `simulation-parity.json`; the `javaSeconds` it records is not a "
						+ "speed figure.",
				ParityDepartures.READ,
				"- The knees: `" + JAVA_KNEES_COMMAND + "` wrote `benchmarks/results/dev/" + KneePairs.JAVA_KNEES
						+ "/` before the Java engine had a version of its own (it names the folder by its version "
						+ "now), and the same harness on the frozen engine, `" + PYTHON_KNEES_COMMAND + "`, "
						+ "`benchmarks/results/dev/" + KneePairs.PYTHON_KNEES + "/`, each over every kept run with a "
						+ "two-pass calibration, the only kind with a knee to re-simulate (`dev/"
						+ KneePairs.FROZEN_ENGINE + "/` predates the spread anchor every check now derives, `dev/"
						+ KneePairs.FROZEN_ENGINE + "-w29/` the held-out runs)."));
		if (speed.timed()) {
			lines.add("- The speed: `" + PYTHON_SPEED_COMMAND + "`, then `" + JAVA_SPEED_COMMAND
					+ "`, one after the other with no other heavy work running.");
		}
		return lines;
	}

}
