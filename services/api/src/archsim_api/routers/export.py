"""Exports (``POST /export``): docker-compose, Kubernetes manifests or a Mermaid diagram of a
design, generated by the engine (empty specs filled with its auto sizes)."""

from __future__ import annotations

from typing import Any, Literal

from fastapi import APIRouter, Depends, HTTPException

from archsim_api.deps import get_registry
from archsim_api.schemas import ApiModel
from archsim_engine import ComponentRegistry, DocumentInvalidError
from archsim_engine.export import FORMATS, export_document

router = APIRouter(tags=["export"])


class ExportRequest(ApiModel):
    document: dict[str, Any]
    format: Literal["compose", "k8s", "mermaid"]


@router.post(
    "/export",
    responses={422: {"description": "The document cannot be read (issues explain why)."}},
)
def export(
    body: ExportRequest, registry: ComponentRegistry = Depends(get_registry)
) -> dict[str, Any]:
    """The design as scaffolding text, with a suggested file suffix and media type."""
    try:
        text = export_document(body.document, body.format, registry)
    except DocumentInvalidError as exc:
        raise HTTPException(
            422,
            detail={
                "message": "The document cannot be exported",
                "issues": [i.to_dict() for i in exc.issues],
            },
        ) from None
    suffix, mime = FORMATS[body.format]
    return {"format": body.format, "text": text, "suffix": suffix, "mediaType": mime}
