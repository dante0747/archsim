def e(source: str, target: str, port: str = "out", **config: Any) -> dict[str, Any]:
    return {
        "id": f"{source}-{target}",
        "source": source,
        "sourcePort": port,
        "target": target,
        "targetPort": "in",
        "config": {
            "requestTypes": ["read", "write"],
            "latencyMs": {"kind": "constant", "value": 1},
            **config,
        },
    }


