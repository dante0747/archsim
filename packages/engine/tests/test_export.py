def doc(raw: dict[str, Any] | None = None) -> dict[str, Any]:
    return load_document(copy.deepcopy(raw or RAW)).to_json_dict()


def test_yaml_quotes_only_what_yaml_would_misread() -> None:
    assert to_yaml(
        {
            "a": "8080:80",
            "b": "true",
            "c": "postgres:16",
            "d": "x: y",
            "e": [],
            "f": {},
            "g": 3,
            "h": None,
        }
    ) == "\n".join(
        [
            'a: "8080:80"',
            'b: "true"',
            "c: postgres:16",
            'd: "x: y"',
            "e: []",
            "f: {}",
            "g: 3",
            "h: null",
        ]
    )
    assert to_yaml({"list": [{"name": "a", "port": 1}, "x"]}) == "\n".join(
        ["list:", "  - name: a", "    port: 1", "  - x"]
    )


def test_compose() -> None:
    out = to_docker_compose(doc(), REGISTRY)
    assert out.startswith('# Generated by ArchSim from "Shop Platform"')
    assert "Starting-point scaffolding" in out
    for text in (
        "image: postgres:16",
        "max_connections=50",
        "image: kong:3.7",
        '"8080:8000"',
        "image: redis:7",
        "image: apache/kafka:3.8.0",
        "db-data:/var/lib/postgresql/data",
    ):
        assert text in out
    assert "image: your-org/api:latest" in out
    assert re.search(r"api:\n(?:.*\n)*?\s+replicas: 2", out)
    assert re.search(r"depends_on:\n\s+- cache\n\s+- db\n\s+- events", out)
    assert "DB_URL: postgresql://db:5432" in out
    assert "x-external-dependencies:" in out and "name: payments" in out
    assert not re.search(r"^ {2}clients:", out, re.M)
    assert "None" not in out and "nan" not in out


def test_kubernetes() -> None:
    out = to_kubernetes(doc(), REGISTRY)
    for text in (
        "kind: HorizontalPodAutoscaler",
        "minReplicas: 2",
        "maxReplicas: 8",
        "averageUtilization: 60",
        "app.kubernetes.io/part-of: shop-platform",
    ):
        assert text in out
    assert re.search(r"kind: StatefulSet\nmetadata:\n\s+name: db\n(?:.*\n)*?\s+replicas: 3", out)
    assert (
        'storage: "10Gi"' in out
        and "mountPath: /var/lib/postgresql/data" in out
        and "clusterIP: None" in out
    )
    assert "apiVersion: serving.knative.dev/v1" in out
    assert 'autoscaling.knative.dev/max-scale: "200"' in out
    assert "type: LoadBalancer" in out and "type: ExternalName" in out
    assert len(out.split("\n---\n")) > 8
    assert "None" not in out.replace("clusterIP: None", "")  # headless Services say None


def test_tiers_in_exports() -> None:
    compose = to_docker_compose(doc(), REGISTRY)
    assert f"# Experimental technologies (Gateway: kong): {TIER_NOTE}" in compose
    assert len(re.findall(r"archsim\.tier: experimental", compose)) == 1
    k8s = to_kubernetes(doc(), REGISTRY)
    assert "# Experimental technologies (Gateway: kong)" in k8s
    assert re.search(
        r"name: gateway\n\s+labels:\n(?:.*\n)*?\s+annotations:\n(?:\s+.*\n)*?\s+archsim/tier: experimental",
        k8s,
    )
    core = copy.deepcopy(RAW)
    core["architecture"]["nodes"] = [
        n for n in core["architecture"]["nodes"] if n["id"] != "gateway"
    ]
    core["architecture"]["edges"] = [
        x for x in core["architecture"]["edges"] if "gateway" not in x["id"]
    ]
    assert "xperimental" not in to_docker_compose(doc(core), REGISTRY)


def test_resource_specs() -> None:
    raw = copy.deepcopy(RAW)
    nodes = {n["id"]: n for n in raw["architecture"]["nodes"]}
    nodes["api"]["config"].update(cpuCores=0.5, memoryGib=1.5)
    nodes["db"]["config"].update(cpuCores=4, memoryGib=16, storageGib=199.5)
    nodes["cache"]["config"].update(cpuCores=2, memoryGib=6.4)
    k8s = to_kubernetes(doc(raw), REGISTRY)
    assert re.search(
        r'name: api\n(?:.*\n)*?\s+resources:\n\s+requests:\n\s+cpu: "500m"\n\s+memory: "1536Mi"\n\s+limits:\n\s+cpu: "500m"\n\s+memory: "1536Mi"',
        k8s,
    )
    assert 'storage: "200Gi"' in k8s and 'memory: "16Gi"' in k8s and 'memory: "6554Mi"' in k8s
    assert 'cpu: "500m"' in to_kubernetes(doc(), REGISTRY)  # placeholder without specs
    compose = to_docker_compose(doc(raw), REGISTRY)
    assert re.search(
        r'api:\n(?:.*\n)*?\s+resources:\n\s+limits:\n\s+cpus: "0.5"\n\s+memory: "1536M"\n\s+reservations:',
        compose,
    )
    assert 'memory: "16G"' in compose
    assert re.search(r'archsim\.storage: "?199\.5 GiB per instance', compose)
    assert "reservations" not in to_docker_compose(doc(), REGISTRY)


def test_mermaid() -> None:
    out = to_mermaid(doc(), REGISTRY)
    assert "flowchart LR" in out
    assert 'clients[/"Clients"/]' in out
    assert 'gateway{{"Gateway · Kong"}}' in out
    assert 'db[("Postgres · PostgreSQL · +2 replicas")]' in out
    assert 'events>"Events · Kafka"]' in out
    assert 'cache -.->|"miss"| db' in out
    assert 'api -->|"writes 500ms"| db' in out
    raw = copy.deepcopy(RAW)
    raw["architecture"] = {
        "nodes": [{"id": "my-db.1", "type": "database", "label": 'Say "hi"', "config": {}}],
        "edges": [],
    }
    assert 'my_db_1[("Say #quot;hi#quot;' in to_mermaid(doc(raw), REGISTRY)


def test_clusters_are_not_deployed() -> None:
    raw = copy.deepcopy(RAW)
    raw["architecture"]["nodes"].append(
        {
            "id": "prod-pool",
            "type": "kubernetes_cluster",
            "label": "prod",
            "config": {"technology": "eks", "nodes": 3},
        }
    )
    assert "name: prod-pool" not in to_kubernetes(doc(raw), REGISTRY)
    import yaml

    compose = yaml.safe_load(to_docker_compose(doc(raw), REGISTRY))
    assert "prod-pool" not in compose["services"]
    # kept for import, not deployed
    assert any(p["id"] == "prod-pool" for p in compose["x-archsim"]["parts"])
    assert "name: api" in to_kubernetes(doc(raw), REGISTRY)


def test_sqs_and_pubsub_get_their_stand_ins() -> None:
    raw = copy.deepcopy(RAW)
    nodes = {n["id"]: n for n in raw["architecture"]["nodes"]}
    nodes["events"]["config"]["technology"] = "sqs"
    compose = to_docker_compose(doc(raw), REGISTRY)
    assert "image: softwaremill/elasticmq-native:1.6.9" in compose
    nodes["events"]["config"]["technology"] = "pubsub"
    compose = to_docker_compose(doc(raw), REGISTRY)
    assert "managed Pub/Sub-style service" in compose


