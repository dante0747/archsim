"""Mermaid flowchart of an architecture document (shapes follow the canvas kinds)."""

from __future__ import annotations

import re
from typing import Any

from archsim_engine.export.tech import (
    DeployNode,
    deploy_nodes,
    num,
    service_replicas,
    technology_label,
)
from archsim_engine.export.yaml import js_number
from archsim_engine.registry import ComponentRegistry

Json = dict[str, Any]


def _esc(s: str) -> str:
    return s.replace('"', "#quot;")


def _mermaid_id(ident: str, taken: set[str]) -> str:
    base = re.sub(r"[^A-Za-z0-9_]", "_", ident)
    if not re.match(r"^[A-Za-z]", base):
        base = f"n_{base}"
    out, i = base, 2
    while out in taken:
        out = f"{base}_{i}"
        i += 1
    taken.add(out)
    return out


def _shape(n: DeployNode, text: str) -> str:
    t = f'"{_esc(text)}"'
    return {
        "traffic": f"[/{t}/]",
        "network": f"{{{{{t}}}}}",
        "compute": f"[[{t}]]",
        "cache": f"([{t}])",
        "database": f"[({t})]",
        "messaging": f">{t}]",
        "external": f"({t})",
    }.get(n.kind, f"[{t}]")


def _caption(n: DeployNode, registry: ComponentRegistry) -> str:
    tech = technology_label(registry, n.node["type"], n.cfg.get("technology"))
    label = n.node.get("label") or n.node["id"]
    parts = [label]
    if tech and tech != "Generic" and tech.lower() not in label.lower():
        parts.append(tech)
    if n.kind == "compute":
        r = service_replicas(n.cfg)
        if n.cfg.get("platform") == "serverless":
            parts.append("serverless")
        elif n.cfg.get("autoscaling") is True:
            parts.append(f"{js_number(r)}–{js_number(num(n.cfg.get('maxReplicas'), r))} replicas")
        else:
            parts.append(f"×{js_number(r)}")
    if n.kind == "database":
        shards = num(n.cfg.get("shards"), 1)
        reps = num(n.cfg.get("readReplicas"), 0)
        if shards > 1:
            parts.append(f"{js_number(shards)} shards")
        if reps > 0:
            parts.append(f"+{js_number(reps)} replicas")
    return " · ".join(parts)


def to_mermaid(doc: Json, registry: ComponentRegistry) -> str:
    nodes = deploy_nodes(doc, registry)
    taken: set[str] = set()
    ids = {n.node["id"]: _mermaid_id(n.node["id"], taken) for n in nodes}
    lines = [
        f'%% Generated by ArchSim from "{_esc(doc["metadata"]["name"])}". Review before publishing.',
        "flowchart LR",
    ]
    for n in nodes:
        lines.append(f"  {ids[n.node['id']]}{_shape(n, _caption(n, registry))}")
    for e in doc["architecture"]["edges"]:
        a, b = ids.get(e["source"]), ids.get(e["target"])
        if not a or not b:
            continue
        cfg = e.get("config") or {}
        types = cfg.get("requestTypes") or []
        label = (
            "miss" if e.get("sourcePort") == "miss" else (f"{types[0]}s" if len(types) == 1 else "")
        )
        timeout = f" {js_number(cfg['timeoutMs'])}ms" if cfg.get("timeoutMs") else ""
        text = f"{label}{timeout}".strip()
        arrow = "-.->" if e.get("sourcePort") == "miss" else "-->"
        lines.append(f"  {a} {arrow}{f'|{_q(text)}|' if text else ''} {b}")
    return "\n".join(lines) + "\n"


def _q(text: str) -> str:
    return f'"{_esc(text)}"'
