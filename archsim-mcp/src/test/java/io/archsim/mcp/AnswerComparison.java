package io.archsim.mcp;

import java.util.List;
import java.util.Map;
import java.util.Set;

import tools.jackson.databind.JsonNode;
import tools.jackson.databind.node.ObjectNode;

import io.archsim.engine.parity.ReportComparison;
import io.archsim.engine.version.EngineVersions;
import io.archsim.model.text.PythonJson;
import io.archsim.parity.JsonDiff;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * An answer of the Java server against the Python server's to the same request: a tool's
 * result by its flag, its contents and its structured content, JSON text and values as
 * the golden files compare them (a report as the simulator's recorded runs are), other
 * text exactly; anything else, an error or a resource with its text, as a JSON value, its
 * strings exactly. The departures of ADR-0058 are checked as they are.
 */
final class AnswerComparison {

	/** What Python answered for an export with a link to a part that is not there. */
	private static final String PYTHONS_KEY_ERROR = "Error executing tool export: 'nowhere'";

	/** Documents given as text that is not an object's JSON. */
	private static final Set<String> DOCUMENTS_NOT_OBJECTS = Set.of("[1]", "{not json");

	/** The SDK validator's refusals of the arguments the input schemas do not allow. */
	private static final Map<String, String> SCHEMA_REFUSALS = Map.of("get_template",
			"Tool (get_template) input validation failed: Validation failed: JSON schema validation errors: "
					+ "[: required property 'id' not found]",
			"breaking_point",
			"Tool (breaking_point) input validation failed: Validation failed: JSON schema validation errors: "
					+ "[/steps: string found, integer expected]");

	private AnswerComparison() {
	}

	/**
	 * Asserts the Java server answered as the Python server did, or as ADR-0058 says it
	 * departs.
	 * @param python the Python server's answer
	 * @param java the Java server's answer
	 * @param request the request both answered
	 */
	static void assertAnsweredAs(JsonNode python, JsonNode java, JsonNode request) {
		String method = request.get("method").stringValue();
		String tool = request.at("/params/name").stringValue("");
		String document = request.at("/params/arguments/document").stringValue("");
		if ("initialize".equals(method)) {
			assertInitializedAs(python, java);
		}
		else if ("nowhere".equals(tool)) {
			assertUnknownToolRefusedBySdk(java);
		}
		else if (DOCUMENTS_NOT_OBJECTS.contains(document)) {
			assertDocumentRefused(document, java);
		}
		else if (refusedBySchema(request, tool)) {
			// the SDK's validator refuses, in its words, what the input schema does not
			// allow: what pydantic refused in its own (no id) or took (a number as text)
			assertThat(java.at("/result/isError").asBoolean()).isTrue();
			assertThat(texts(java)).singleElement().isEqualTo(SCHEMA_REFUSALS.get(tool));
		}
		else if (List.of(PYTHONS_KEY_ERROR).equals(texts(python))) {
			// the export the API gives, where Python failed on the missing part
			assertThat(java.at("/result/isError").asBoolean()).isFalse();
			assertThat(texts(java)).singleElement().asString().startsWith("%% Generated by ArchSim");
		}
		else {
			assertSameAnswer(python, java);
		}
	}

	// a document given as text that is not an object's JSON
	private static void assertDocumentRefused(String document, JsonNode java) {
		if ("[1]".equals(document)) {
			// the text, where the Python SDK read it as the list it holds
			assertThat(texts(java)).containsExactly("Error executing tool validate_design: "
					+ "document must be an ArchSim architecture document (a JSON object)");
		}
		else {
			// not JSON past its first character: Jackson's words, at json's place
			assertThat(texts(java)).singleElement()
				.asString()
				.startsWith("Error executing tool validate_design: document is not valid JSON: ")
				.endsWith(": line 1 column 2 (char 1)");
		}
	}

	// get_template without its id, breaking_point with its steps as text
	private static boolean refusedBySchema(JsonNode request, String tool) {
		JsonNode arguments = request.at("/params/arguments");
		boolean noId = "get_template".equals(tool) && !arguments.has("id");
		return noId || arguments.path("steps").isString();
	}

	private static void assertUnknownToolRefusedBySdk(JsonNode java) {
		// the SDK's JSON-RPC error, where the Python SDK answered with a refusal
		JsonNode error = java.get("error");
		assertThat(List.of(error.path("code").asInt(), error.path("message").asString(), error.path("data").asString()))
			.containsExactly(-32602, "Unknown tool: invalid_tool_name", "Tool not found: nowhere");
	}

	private static void assertInitializedAs(JsonNode python, JsonNode java) {
		// the SDK requires a version, and declares logging
		assertThat(java.at("/result/serverInfo/version").stringValue()).isEqualTo(EngineVersions.ENGINE);
		assertThat(java.at("/result/capabilities/logging").isObject()).isTrue();
		JsonNode answered = java.deepCopy();
		((ObjectNode) answered.at("/result/serverInfo")).put("version", "");
		((ObjectNode) answered.at("/result/capabilities")).remove("logging");
		assertThat(JsonDiff.differences(python, answered)).isEmpty();
	}

	private static void assertSameAnswer(JsonNode python, JsonNode java) {
		JsonNode expected = python.path("result");
		JsonNode actual = java.path("result");
		if (expected.has("content")) {
			assertSameResult(expected, actual);
		}
		else if (expected.has("contents")) {
			assertSameResource(expected.get("contents"), actual.get("contents"));
		}
		else {
			assertThat(JsonDiff.differences(python, java)).isEmpty();
		}
	}

	// a resource's JSON by its values, laid out as json.dumps(value, indent=1) laid out
	// Python's (the schema's keys in the Java model's order); other text exactly
	private static void assertSameResource(JsonNode python, JsonNode java) {
		assertThat(java.size()).isEqualTo(python.size());
		for (int i = 0; i < python.size(); i++) {
			assertThat(java.get(i).path("uri")).isEqualTo(python.get(i).path("uri"));
			assertThat(java.get(i).path("mimeType")).isEqualTo(python.get(i).path("mimeType"));
			String expected = python.get(i).path("text").stringValue("");
			String actual = java.get(i).path("text").stringValue("");
			if (expected.startsWith("{")) {
				JsonNode value = McpSession.JSON.readTree(expected);
				assertThat(PythonJson.writeIndented(value, 1)).isEqualTo(expected);
				JsonNode written = McpSession.JSON.readTree(actual);
				assertThat(JsonDiff.differences(value, written)).isEmpty();
				assertThat(actual).isEqualTo(PythonJson.writeIndented(written, 1));
			}
			else {
				assertThat(actual).isEqualTo(expected);
			}
		}
	}

	private static void assertSameResult(JsonNode python, JsonNode java) {
		assertThat(java.path("isError").asBoolean()).isEqualTo(python.path("isError").asBoolean());
		List<String> expected = texts(python);
		List<String> actual = texts(java);
		assertThat(actual).hasSameSizeAs(expected);
		for (int i = 0; i < expected.size(); i++) {
			assertSameText(expected.get(i), actual.get(i));
		}
		assertThat(java.has("structuredContent")).isEqualTo(python.has("structuredContent"));
		if (python.has("structuredContent")) {
			assertSameValue(python.get("structuredContent"), java.get("structuredContent"));
		}
	}

	// JSON by its values, written as pydantic_core.to_json(value, indent=2) wrote
	// Python's: the writer gives Python's text from Python's value, Java's from Java's
	private static void assertSameText(String python, String java) {
		if (python.startsWith("{") || python.startsWith("[")) {
			JsonNode value = McpSession.JSON.readTree(python);
			assertThat(PythonJson.writePydantic(value, 2)).isEqualTo(python);
			JsonNode written = McpSession.JSON.readTree(java);
			assertSameValue(value, written);
			assertThat(java).isEqualTo(PythonJson.writePydantic(written, 2));
		}
		else {
			assertThat(java).isEqualTo(python);
		}
	}

	private static void assertSameValue(JsonNode python, JsonNode java) {
		if (python.has("reportVersion") && python.has("provenance")) {
			assertThat(ReportComparison.differences(python, java)).isEmpty();
		}
		else {
			assertThat(JsonDiff.differences(python, java)).isEmpty();
		}
	}

	private static List<String> texts(JsonNode answer) {
		JsonNode result = answer.has("result") ? answer.get("result") : answer;
		return result.path("content").valueStream().map((content) -> content.path("text").stringValue("")).toList();
	}

}
