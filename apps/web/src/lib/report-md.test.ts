import { describe, expect, it } from "vitest";
import analysisJson from "@/test/fixtures/analysis-starter.json";
import catalogJson from "@/test/fixtures/catalog.json";
import starter from "@/test/fixtures/starter.json";
import { cell, decisionReportMarkdown } from "./report-md";
import type { Analysis, ArchitectureDocument, Catalog, Report } from "./types";

const doc = starter as unknown as ArchitectureDocument;
const catalog = catalogJson as unknown as Catalog;

function fakeReport(over: { p95?: number; successRate?: number } = {}): Report {
  const successRate = over.successRate ?? 0.9995;
  return {
    summary: {
      offeredRps: 400,
      throughputRps: 399,
      successRate,
      timeoutRate: 0,
      retryAmplification: 1,
      latencyMs: { p50: 30, p95: over.p95 ?? 89, p99: 120 },
      accounting: { measured: { arrived: 20000, succeeded: 19990, failed: 10, timedOut: 0, outstanding: 0 } },
    },
    findings: [
      { severity: "critical", kind: "bottleneck", nodeId: "api", title: "API Servers is the primary bottleneck", detail: "Busy 100%.", suggestion: "Add replicas.", evidence: {} },
    ],
    nodes: [],
    input: { architecture: doc.architecture, workload: doc.workload, schemaVersion: "1.0", metadata: { name: "x" } },
    assumptions: { userInputs: [{}, {}, {}] },
    provenance: { seed: 42, engineVersion: "0.1.0", requestsGenerated: 23980, inputDigest: "abcdef0123456789", resultDigest: "0123456789abcdef" },
  } as unknown as Report;
}

describe("decision report", () => {
  it("summarises design, objectives, results, findings and assumptions", () => {
    const md = decisionReportMarkdown({
      doc,
      catalog,
      objectives: { latencyP95Ms: 300, availability: 0.999 },
      report: fakeReport(),
      run: { label: "Baseline" } as never,
      generatedAt: new Date("2026-10-24T12:00:00Z"),
    });
    expect(md).toContain(`# ${doc.metadata.name}: design decision report`);
    expect(md).toContain("Generated by ArchSim on 2026-10-24T12:00:00Z");
    expect(md).toContain("**Verdict:** Meets all objectives");
    expect(md).toContain("| Latency p95 | ≤ 300 ms | 89 ms | pass |");
    expect(md).toContain("**API Servers is the primary bottleneck** (critical). Busy 100%. Try: Add replicas.");
    expect(md).toContain("## Design");
    for (const n of doc.architecture.nodes) expect(md).toContain(n.label);
    expect(md).toContain("3 values marked as assumptions");
    expect(md).toContain("Error budget: 10 failed requests against 20 allowed");
  });

  it("marks experimental technologies in the design and the assumptions", () => {
    expect(decisionReportMarkdown({ doc, catalog, objectives: {} })).not.toContain("xperimental");
    const mongo = structuredClone(doc);
    const db = mongo.architecture.nodes.find((n) => n.type === "database")!;
    db.config = { ...db.config, technology: "mongodb" };
    const md = decisionReportMarkdown({ doc: mongo, catalog, objectives: {} });
    expect(md).toMatch(/\| MongoDB \(experimental\) \|/);
    expect(md).toContain(`Experimental technologies (${db.label}): ${catalog.tierNote}`);
  });

  it("flags failed objectives and works without a run", () => {
    const failing = decisionReportMarkdown({ doc, catalog, objectives: { latencyP95Ms: 50 }, report: fakeReport({ p95: 89 }) });
    expect(failing).toContain("Misses 1 of 1 objectives");
    expect(failing).toContain("**FAIL**");
    const none = decisionReportMarkdown({ doc, catalog, objectives: {} });
    expect(none).toContain("No simulation run yet");
    expect(none).toContain("No objectives set.");
  });

  it("includes faults, review items and the breaking point when given", () => {
    const withFaults = { ...doc, workload: { ...doc.workload, faults: [{ id: "f1", kind: "outage" as const, target: "cache", startS: 10, durationS: 5 }] } };
    const md = decisionReportMarkdown({
      doc: withFaults,
      catalog,
      objectives: {},
      review: [{ severity: "warning", title: "Single point of failure", detail: "PostgreSQL has one node." }],
      sweep: { rows: [{ rps: 100, runId: null, offered: 100, throughput: 100, p50: 5, p95: 10, p99: 20, p95WithFailures: 10, successRate: 1, errorRate: 0, bottleneck: null }], knee: null, kneeReason: null, maxWithinSlo: null, saturatedAt: null, failingFrom: null, verdict: "Holds 100 req/s." },
    });
    expect(md).toContain("outage on `cache` from 10 s for 5 s");
    expect(md).toContain("**Single point of failure** (warning): PostgreSQL has one node.");
    expect(md).toContain("## Breaking point");
    expect(md).toContain("Holds 100 req/s.");
  });

  it("carries the run's confidence, its estimate against the simulation and documented inputs", () => {
    const analysis = analysisJson as unknown as Analysis;
    const report = fakeReport();
    report.confidence = analysis.confidence;
    report.estimate = analysis.estimate;
    report.nodes = [{ id: "api", summary: { utilization: 0.698 } }] as unknown as Report["nodes"];
    report.assumptions = {
      ...report.assumptions,
      provenanceCounts: { measured: 0, documented: 1, assumed: 4, illustrative: 30 },
      userInputs: [
        { scope: "node", id: "api", label: "API Servers", field: "gcPauseMs", fieldLabel: "GC pause", value: "0.1 ms", provenance: { kind: "documented", source: "https://go.dev/doc/go1.8", note: "default for go" } },
      ],
    };
    const md = decisionReportMarkdown({ doc, catalog, objectives: { latencyP95Ms: 300 }, report });
    expect(md).toContain("- **Low confidence:** 31 of 35 inputs are illustrative defaults. To raise it: Calibrate from telemetry");
    expect(md).toContain("### Confidence: low");
    expect(md).toContain("| API Servers: Service time | illustrative |");
    expect(md).toContain("Queueing formulas: p95 ≈ 97 ms (simulated 89 ms); API Servers 70% busy (simulated 70%).");
    expect(md).toContain("Inputs: 0 measured from telemetry, 1 documented by the vendor, 4 assumed (typed in), 30 illustrative");
    expect(md).toContain("| API Servers: GC pause | 0.1 ms | https://go.dev/doc/go1.8 |");
  });

  it("uses the design's confidence and estimate without a run", () => {
    const analysis = analysisJson as unknown as Analysis;
    const md = decisionReportMarkdown({ doc, catalog, objectives: {}, designConfidence: analysis.confidence, designEstimate: analysis.estimate });
    expect(md).toContain("- **Estimate from queueing formulas (not simulated):** p95 ≈ ");
    expect(md).toContain("- **Low confidence:** 31 of 35 inputs are illustrative defaults.");
    // a run made before confidence was recorded borrows the design's, and says so
    const old = decisionReportMarkdown({ doc, catalog, objectives: {}, report: fakeReport(), designConfidence: analysis.confidence });
    expect(old).toContain("**Low confidence (current design; the run predates confidence):**");
  });

  it("escapes table cells", () => {
    expect(cell("a|b\nc")).toBe("a\\|b c");
  });
});
