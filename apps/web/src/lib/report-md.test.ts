import { describe, expect, it } from "vitest";
import catalogJson from "@/test/fixtures/catalog.json";
import starter from "@/test/fixtures/starter.json";
import { cell, decisionReportMarkdown } from "./report-md";
import type { ArchitectureDocument, Catalog, Report } from "./types";

const doc = starter as unknown as ArchitectureDocument;
const catalog = catalogJson as unknown as Catalog;

function fakeReport(over: { p95?: number; successRate?: number } = {}): Report {
  const successRate = over.successRate ?? 0.9995;
  return {
    summary: {
      offeredRps: 400,
      throughputRps: 399,
      successRate,
      timeoutRate: 0,
      retryAmplification: 1,
      latencyMs: { p50: 30, p95: over.p95 ?? 89, p99: 120 },
      accounting: { measured: { arrived: 20000, succeeded: 19990, failed: 10, timedOut: 0, outstanding: 0 } },
    },
    findings: [
      { severity: "critical", kind: "bottleneck", nodeId: "api", title: "API Servers is the primary bottleneck", detail: "Busy 100%.", suggestion: "Add replicas.", evidence: {} },
    ],
    nodes: [],
    input: { architecture: doc.architecture, workload: doc.workload, schemaVersion: "1.0", metadata: { name: "x" } },
    assumptions: { userInputs: [{}, {}, {}] },
    provenance: { seed: 42, engineVersion: "0.1.0", requestsGenerated: 23980, inputDigest: "abcdef0123456789", resultDigest: "0123456789abcdef" },
  } as unknown as Report;
}

describe("decision report", () => {
  it("summarises design, objectives, results, findings and assumptions", () => {
    const md = decisionReportMarkdown({
      doc,
      catalog,
      objectives: { latencyP95Ms: 300, availability: 0.999 },
      report: fakeReport(),
      run: { label: "Baseline" } as never,
      generatedAt: new Date("2026-10-24T12:00:00Z"),
    });
    expect(md).toContain(`# ${doc.metadata.name}: design decision report`);
    expect(md).toContain("Generated by ArchSim on 2026-10-24T12:00:00Z");
    expect(md).toContain("**Verdict:** Meets all objectives");
    expect(md).toContain("| Latency p95 | ≤ 300 ms | 89 ms | pass |");
    expect(md).toContain("**API Servers is the primary bottleneck** (critical). Busy 100%. Try: Add replicas.");
    expect(md).toContain("## Design");
    for (const n of doc.architecture.nodes) expect(md).toContain(n.label);
    expect(md).toContain("3 values marked as assumptions");
    expect(md).toContain("Error budget: 10 failed requests against 20 allowed");
  });

  it("flags failed objectives and works without a run", () => {
    const failing = decisionReportMarkdown({ doc, catalog, objectives: { latencyP95Ms: 50 }, report: fakeReport({ p95: 89 }) });
    expect(failing).toContain("Misses 1 of 1 objectives");
    expect(failing).toContain("**FAIL**");
    const none = decisionReportMarkdown({ doc, catalog, objectives: {} });
    expect(none).toContain("No simulation run yet");
    expect(none).toContain("No objectives set.");
  });

  it("includes faults, review items and the breaking point when given", () => {
    const withFaults = { ...doc, workload: { ...doc.workload, faults: [{ id: "f1", kind: "outage" as const, target: "cache", startS: 10, durationS: 5 }] } };
    const md = decisionReportMarkdown({
      doc: withFaults,
      catalog,
      objectives: {},
      review: [{ severity: "warning", title: "Single point of failure", detail: "PostgreSQL has one node." }],
      sweep: { rows: [{ rps: 100, runId: null, offered: 100, throughput: 100, p50: 5, p95: 10, p99: 20, successRate: 1, errorRate: 0, bottleneck: null }], knee: null, kneeReason: null, maxWithinSlo: null, saturatedAt: null, verdict: "Holds 100 req/s." },
    });
    expect(md).toContain("outage on `cache` from 10 s for 5 s");
    expect(md).toContain("**Single point of failure** (warning): PostgreSQL has one node.");
    expect(md).toContain("## Breaking point");
    expect(md).toContain("Holds 100 req/s.");
  });

  it("escapes table cells", () => {
    expect(cell("a|b\nc")).toBe("a\\|b c");
  });
});
