/**
 * Metric registry: what every time series in a report means, its unit, how the engine computes it
 * and which dashboard panel shows it. System series (report.timeseries) and component series
 * (report.nodes[].timeseries) live in separate scopes because a few keys exist in both with
 * different meanings (latencyP95Ms is end-to-end for the system, time inside one part for a node).
 * Keys this registry does not know fall back to a humanized label and a unit guessed from the name.
 */

export type MetricKind = "rate" | "ratio" | "gauge" | "latency" | "count";
export type MetricUnit = "req/s" | "/s" | "ms" | "ratio" | "count" | "messages" | "units/s";
export type MetricScope = "system" | "node" | "derived";
export type ThresholdStatus = "good" | "warning" | "serious" | "critical";

export interface MetricThresholds {
  /** "above": higher values are worse; "below": lower values are worse. */
  direction: "above" | "below";
  /** Ordered from the mildest to the worst step. */
  steps: { value: number; status: Exclude<ThresholdStatus, "good"> }[];
}

/** Panel groups: metrics of one component that share a unit and a story end up in one panel. */
export type PanelGroupId =
  | "overview"
  | "traffic"
  | "attempts"
  | "latency"
  | "requests"
  | "utilization"
  | "queue"
  | "componentLatency"
  | "hitRatio"
  | "evictions"
  | "instances"
  | "pods"
  | "clusterNodes"
  | "requested"
  | "coldStarts"
  | "pauses"
  | "waits"
  | "reads"
  | "capacityUnits"
  | "backlog"
  | "delivery"
  | "limits";

export interface PanelGroup {
  id: PanelGroupId;
  title: string;
  unit: MetricUnit;
}

export interface MetricDef {
  key: string;
  scope: MetricScope;
  label: string;
  /** Legend name inside a component's own panel, where the component is already known ("p95"). */
  short: string;
  unit: MetricUnit;
  kind: MetricKind;
  description: string;
  /** One or two plain sentences on how the engine derives the value. */
  howCalculated: string;
  /** Default panel. */
  panel: PanelGroupId;
  /** Colour slot (1-8, var(--series-N)) inside its panel, so a metric keeps its colour everywhere. */
  slot: number;
  thresholds?: MetricThresholds;
  /** Upper bound of the value range (ratios: 1). */
  max?: number;
  /** Which way is good, when one is. */
  better?: "higher" | "lower";
  /** Component types that emit the series (documentation only: the dashboard reads what is present). */
  emittedBy?: string[];
  /** True when the registry has no entry and the definition was guessed from the key. */
  fallback?: boolean;
}

