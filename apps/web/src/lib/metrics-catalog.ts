const DASH = "–";

function compactNum(v: number): string {
  const a = Math.abs(v);
  if (a >= 1e6) return `${(v / 1e6).toFixed(a >= 1e7 ? 0 : 1)}M`;
  if (a >= 1e4) return `${(v / 1e3).toFixed(0)}k`;
  if (a >= 1e3) return `${(v / 1e3).toFixed(1)}k`;
  if (a >= 100) return String(Math.round(v));
  if (a >= 10) return v.toFixed(1).replace(/\.0$/, "");
  if (a >= 1) return v.toFixed(2).replace(/\.?0+$/, "");
  if (a === 0) return "0";
  return v.toFixed(a >= 0.1 ? 2 : 3).replace(/\.?0+$/, "");
}

function fmtMsValue(v: number): string {
  const a = Math.abs(v);
  if (a >= 10_000) return `${(v / 1000).toFixed(1)} s`;
  if (a >= 1000) return `${(v / 1000).toFixed(2)} s`;
  if (a >= 100) return `${v.toFixed(0)} ms`;
  if (a >= 10) return `${v.toFixed(1)} ms`;
  if (a >= 1) return `${v.toFixed(2)} ms`;
  if (a === 0) return "0 ms";
  return `${+v.toPrecision(2)} ms`;
}

/** Percent with the precision that matters: "99.97%" near 100, "42%", "3.5%", "0.12%". */
function fmtRatio(v: number): string {
  const p = v * 100;
  const a = Math.abs(p);
  if (a === 0) return "0%";
  if (a >= 99.95 && a < 100) return `${p.toFixed(2)}%`;
  if (a >= 99.5 && a < 100) return `${p.toFixed(1)}%`;
  if (a >= 10) return `${p.toFixed(0)}%`;
  if (a >= 1) return `${p.toFixed(1)}%`;
  return `${p.toFixed(2)}%`;
}

/** A value with its unit for tooltips, legends and stats: "412 req/s", "123 ms", "95%". */
export function formatValue(v: number | null | undefined, unit: MetricUnit): string {
  if (v == null || !Number.isFinite(v)) return DASH;
  switch (unit) {
    case "ms":
      return fmtMsValue(v);
    case "ratio":
      return fmtRatio(v);
    case "req/s":
      return `${compactNum(v)} req/s`;
    case "/s":
      return `${compactNum(v)}/s`;
    case "units/s":
      return `${compactNum(v)} units/s`;
    case "messages":
      return `${compactNum(v)} msgs`;
    default:
      return compactNum(v);
  }
}

/** Legend cell: like formatValue with shorter units ("412/s", "300"), so columns stay narrow. */
export function formatCompact(v: number | null | undefined, unit: MetricUnit): string {
  if (v == null || !Number.isFinite(v)) return DASH;
  if (unit === "req/s" || unit === "/s" || unit === "units/s") return `${compactNum(v)}/s`;
  if (unit === "ms" || unit === "ratio") return formatValue(v, unit);
  return compactNum(v);
}

/** Short axis tick label: "1.2k", "250 ms", "40%". */
export function formatTick(v: number, unit: MetricUnit): string {
  if (!Number.isFinite(v)) return "";
  // toPrecision keeps small steps apart (0.01 ms, 0.02 ms) where toFixed would print "0" twice.
  if (unit === "ms") {
    if (v === 0) return "0";
    return Math.abs(v) >= 1000 ? `${+(v / 1000).toPrecision(3)} s` : `${+v.toPrecision(3)} ms`;
  }
  if (unit === "ratio") return `${+(v * 100).toPrecision(3)}%`;
  return compactNum(v);
}

/** Unit as shown next to a panel title or axis. */
export function unitLabel(unit: MetricUnit): string {
  switch (unit) {
    case "ratio":
      return "%";
    case "count":
      return "count";
    default:
      return unit;
  }
}
