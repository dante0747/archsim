const build = (scope: MetricScope, defs: Record<string, Def>): Record<string, MetricDef> =>
  Object.fromEntries(Object.entries(defs).map(([key, d]) => [key, { key, scope, ...d }]));

export const SYSTEM_METRICS: Record<string, MetricDef> = build("system", SYSTEM);
export const NODE_METRICS: Record<string, MetricDef> = build("node", NODE);
export const DERIVED_METRICS: Record<string, MetricDef> = build("derived", DERIVED);

const BY_SCOPE: Record<MetricScope, Record<string, MetricDef>> = { system: SYSTEM_METRICS, node: NODE_METRICS, derived: DERIVED_METRICS };

/** "replicationLagMs" → "Replication lag", "p99QueueWait" → "P99 queue wait". */
export function humanizeKey(key: string): string {
  const base = key.replace(/(Ms|Rps|Ratio)$/, "");
  const words = base
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .replace(/([A-Z])([A-Z][a-z])/g, "$1 $2")
    .replace(/[_-]+/g, " ")
    .trim()
    .toLowerCase();
  if (!words) return key;
  return words.charAt(0).toUpperCase() + words.slice(1);
}

/** Unit guessed from a key's suffix, for series the registry does not know. */
export function guessUnit(key: string): MetricUnit {
  if (/Ms$/.test(key)) return "ms";
  if (/Rps$/.test(key)) return "/s";
  if (/(Ratio|Utilization)$/.test(key)) return "ratio";
  return "count";
}

const KIND_OF_UNIT: Record<MetricUnit, MetricKind> = {
  "req/s": "rate",
  "/s": "rate",
  ms: "latency",
  ratio: "ratio",
  count: "gauge",
  messages: "gauge",
  "units/s": "rate",
};

/** Definition of a metric, or a humanized fallback for keys the registry does not know. */
export function metricDef(key: string, scope: MetricScope = "node"): MetricDef {
  const known = BY_SCOPE[scope][key];
  if (known) return known;
  const unit = guessUnit(key);
  const label = humanizeKey(key);
  return {
    key,
    scope,
    label,
    short: label,
    unit,
    kind: KIND_OF_UNIT[unit],
    description: `Series “${key}” reported by the engine.`,
    howCalculated: "Not documented yet: the value as the engine reports it for each bucket.",
    panel: "requests",
    slot: 1,
    max: unit === "ratio" ? 1 : undefined,
    fallback: true,
  };
}

export function panelGroup(id: PanelGroupId): PanelGroup {
  return PANEL_GROUPS.find((g) => g.id === id) ?? { id, title: humanizeKey(id), unit: "count" };
}

/** Status of a value against thresholds ("good" below the first step, or with none set). */
export function thresholdStatus(value: number | null | undefined, t: MetricThresholds | null | undefined): ThresholdStatus | null {
  if (value == null || !Number.isFinite(value)) return null;
  if (!t || !t.steps.length) return null;
  let status: ThresholdStatus = "good";
  for (const s of t.steps) {
    if (t.direction === "above" ? value >= s.value : value < s.value) status = s.status;
  }
  return status;
}

