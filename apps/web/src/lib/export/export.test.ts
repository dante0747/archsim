import { describe, expect, it } from "vitest";
import catalogJson from "@/test/fixtures/catalog.json";
import { DEFAULT_WORKLOAD } from "@/lib/document";
import type { ArchitectureDocument, Catalog, EdgeConfig } from "@/lib/types";
import { toDockerCompose } from "./compose";
import { toKubernetes } from "./k8s";
import { toMermaid } from "./mermaid";
import { toYaml } from "./yaml";

const catalog = catalogJson as unknown as Catalog;

const e = (source: string, target: string, config: Partial<EdgeConfig> = {}, sourcePort = "out") => ({
  id: `${source}-${target}`,
  source,
  sourcePort,
  target,
  targetPort: "in",
  config: { requestTypes: ["read", "write"] as ("read" | "write")[], latencyMs: { kind: "constant" as const, value: 1 }, ...config },
});

const doc: ArchitectureDocument = {
  schemaVersion: "1.0",
  kind: "archsim.architecture",
  metadata: { name: "Shop Platform" },
  architecture: {
    nodes: [
      { id: "clients", type: "traffic_source", label: "Clients", config: {} },
      { id: "gateway", type: "load_balancer", label: "Gateway", config: { technology: "kong", rateLimitRps: 500 } },
      { id: "api", type: "service", label: "API", config: { platform: "kubernetes", autoscaling: true, minReplicas: 2, maxReplicas: 8, targetUtilization: 0.6, replicas: 2 } },
      { id: "thumbs", type: "service", label: "Thumbnailer", config: { platform: "serverless", concurrencyLimit: 200, workersPerReplica: 1 } },
      { id: "cache", type: "cache", label: "Redis", config: { technology: "redis" } },
      { id: "db", type: "database", label: "Postgres", config: { technology: "postgresql", readReplicas: 2, maxConnections: 50 } },
      { id: "events", type: "message_queue", label: "Events", config: { technology: "kafka", partitions: 6, consumers: 3, brokers: 3 } },
      { id: "payments", type: "external_api", label: "Payments", config: { technology: "payments" } },
    ],
    edges: [
      e("clients", "gateway"),
      e("gateway", "api", { timeoutMs: 2000 }),
      e("api", "cache", { requestTypes: ["read"], timeoutMs: 50 }),
      e("cache", "db", { requestTypes: ["read"] }, "miss"),
      e("api", "db", { requestTypes: ["write"], timeoutMs: 500 }),
      e("api", "events", { requestTypes: ["write"] }),
      e("events", "thumbs"),
      e("api", "payments", { requestTypes: ["write"], timeoutMs: 3000 }),
    ],
  },
  workload: { ...DEFAULT_WORKLOAD, rps: 400 },
  scenarios: [],
  layout: { nodes: {} },
};

describe("toYaml", () => {
  it("quotes only what YAML would misread", () => {
    expect(toYaml({ a: "8080:80", b: "true", c: "postgres:16", d: "x: y", e: [], f: {}, g: 3, h: null, i: undefined })).toBe(
      ['a: "8080:80"', 'b: "true"', "c: postgres:16", 'd: "x: y"', "e: []", "f: {}", "g: 3", "h: null"].join("\n"),
    );
    expect(toYaml({ list: [{ name: "a", port: 1 }, "x"] })).toBe(["list:", "  - name: a", "    port: 1", "  - x"].join("\n"));
  });
});

describe("toDockerCompose", () => {
  const out = toDockerCompose(doc, catalog);
  it("starts with the scaffolding disclaimer", () => {
    expect(out.startsWith("# Generated by ArchSim from \"Shop Platform\"")).toBe(true);
    expect(out).toContain("Starting-point scaffolding");
  });
  it("maps technologies to images with model values", () => {
    expect(out).toContain("image: postgres:16");
    expect(out).toContain("max_connections=50");
    expect(out).toContain("image: kong:3.7");
    expect(out).toContain('"8080:8000"');
    expect(out).toContain("image: redis:7");
    expect(out).toContain("image: apache/kafka:3.8.0");
    expect(out).toContain("db-data:/var/lib/postgresql/data");
  });
  it("deploys app services with replicas, dependencies and URLs", () => {
    expect(out).toContain("image: your-org/api:latest");
    expect(out).toMatch(/api:\n(?:.*\n)*?\s+replicas: 2/);
    expect(out).toMatch(/depends_on:\n\s+- cache\n\s+- db\n\s+- events/);
    expect(out).toContain("DB_URL: postgresql://db:5432");
  });
  it("lists third-party APIs as external dependencies and skips the clients", () => {
    expect(out).toContain("x-external-dependencies:");
    expect(out).toContain("name: payments");
    expect(out).not.toMatch(/^ {2}clients:/m);
    expect(out).not.toMatch(/undefined|NaN/);
  });
});

describe("toKubernetes", () => {
  const out = toKubernetes(doc, catalog);
  it("emits deployments, services and an HPA from autoscaling settings", () => {
    expect(out).toContain("kind: HorizontalPodAutoscaler");
    expect(out).toContain("minReplicas: 2");
    expect(out).toContain("maxReplicas: 8");
    expect(out).toContain("averageUtilization: 60");
    expect(out).toContain("app.kubernetes.io/part-of: shop-platform");
  });
  it("uses StatefulSets for stores (replicas = primary + read replicas) and brokers", () => {
    expect(out).toMatch(/kind: StatefulSet\nmetadata:\n\s+name: db\n(?:.*\n)*?\s+replicas: 3/);
    expect(out).toContain('storage: "10Gi"');
    expect(out).toContain("mountPath: /var/lib/postgresql/data");
    expect(out).toContain("clusterIP: None");
  });
  it("covers serverless, gateways and third-party APIs", () => {
    expect(out).toContain("apiVersion: serving.knative.dev/v1");
    expect(out).toContain('autoscaling.knative.dev/max-scale: "200"');
    expect(out).toContain("type: LoadBalancer");
    expect(out).toContain("type: ExternalName");
    expect(out.split("\n---\n").length).toBeGreaterThan(8);
    expect(out).not.toMatch(/undefined|NaN/);
  });
});

describe("technology tiers in exports", () => {
  it("marks experimental technologies (Kong here) and leaves core ones alone", () => {
    const compose = toDockerCompose(doc, catalog);
    expect(compose).toContain("# Experimental technologies (Gateway: kong): " + catalog.tierNote);
    expect(compose.match(/archsim\.tier: experimental/g)).toHaveLength(1);
    expect(compose).toMatch(/gateway:\n(?:.*\n)*?\s+archsim\.tier: experimental/);
    const k8s = toKubernetes(doc, catalog);
    expect(k8s).toContain("# Experimental technologies (Gateway: kong)");
    expect(k8s).toMatch(/name: gateway\n\s+labels:\n(?:.*\n)*?\s+annotations:\n\s+archsim\/tier: experimental/);
    const allCore = structuredClone(doc);
    allCore.architecture.nodes = allCore.architecture.nodes.filter((n) => n.id !== "gateway");
    expect(toDockerCompose(allCore, catalog)).not.toContain("xperimental");
  });
});

describe("resource specs in exports", () => {
  const sized: ArchitectureDocument = structuredClone(doc);
  const set = (id: string, cfg: Record<string, unknown>) => {
    const n = sized.architecture.nodes.find((x) => x.id === id)!;
    n.config = { ...n.config, ...cfg };
  };
  set("api", { cpuCores: 0.5, memoryGib: 1.5 });
  set("db", { cpuCores: 4, memoryGib: 16, storageGib: 199.5 });
  set("cache", { cpuCores: 2, memoryGib: 6.4 });

  it("writes Kubernetes requests and limits and the volume size from the specs", () => {
    const out = toKubernetes(sized, catalog);
    expect(out).toMatch(/name: api\n(?:.*\n)*?\s+resources:\n\s+requests:\n\s+cpu: "500m"\n\s+memory: "1536Mi"\n\s+limits:\n\s+cpu: "500m"\n\s+memory: "1536Mi"/);
    expect(out).toContain('storage: "200Gi"');
    expect(out).toContain('memory: "16Gi"');
    expect(out).toContain('memory: "6554Mi"');
    // parts without specs keep the placeholder
    expect(toKubernetes(doc, catalog)).toContain('cpu: "500m"');
    expect(out).not.toMatch(/undefined|NaN/);
  });

  it("writes Compose limits and reservations, and notes storage", () => {
    const out = toDockerCompose(sized, catalog);
    expect(out).toMatch(/api:\n(?:.*\n)*?\s+resources:\n\s+limits:\n\s+cpus: "0.5"\n\s+memory: "1536M"\n\s+reservations:/);
    expect(out).toContain('memory: "16G"');
    expect(out).toMatch(/archsim\.storage: "?199\.5 GiB per instance/);
    expect(toDockerCompose(doc, catalog)).not.toContain("reservations");
  });
});

describe("toMermaid", () => {
  const out = toMermaid(doc, catalog);
  it("draws kinds with matching shapes and labels edges", () => {
    expect(out).toContain("flowchart LR");
    expect(out).toContain('clients[/"Clients"/]');
    expect(out).toContain('gateway{{"Gateway · Kong"}}');
    expect(out).toContain('db[("Postgres · PostgreSQL · +2 replicas")]');
    expect(out).toContain('events>"Events · Kafka"]');
    expect(out).toContain('cache -.->|"miss"| db');
    expect(out).toContain('api -->|"writes 500ms"| db');
  });
  it("sanitizes ids", () => {
    const d2: ArchitectureDocument = {
      ...doc,
      architecture: { nodes: [{ id: "my-db.1", type: "database", label: 'Say "hi"', config: {} }], edges: [] },
    };
    expect(toMermaid(d2, catalog)).toContain('my_db_1[("Say #quot;hi#quot;');
  });
});

describe("Kubernetes cluster parts in exports", () => {
  const withCluster: ArchitectureDocument = {
    ...doc,
    architecture: {
      ...doc.architecture,
      nodes: [...doc.architecture.nodes, { id: "prod-pool", type: "kubernetes_cluster", label: "prod", config: { technology: "eks", nodes: 3 } }],
    },
  };
  it("deploys the workloads, not the cluster they run on", () => {
    expect(toKubernetes(withCluster, catalog)).not.toContain("name: prod-pool");
    expect(toDockerCompose(withCluster, catalog)).not.toContain("prod-pool");
    expect(toKubernetes(withCluster, catalog)).toContain("name: api");
  });
});
