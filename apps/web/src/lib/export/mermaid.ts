/** Mermaid flowchart of an architecture document (shapes follow the canvas kinds). */
import { technologyLabel } from "@/lib/theme";
import type { ArchitectureDocument, Catalog } from "@/lib/types";
import { deployNodes, num, serviceReplicas, type DeployNode } from "./tech";

const esc = (s: string) => s.replace(/"/g, "#quot;");

function mermaidId(id: string, taken: Set<string>): string {
  let base = id.replace(/[^A-Za-z0-9_]/g, "_");
  if (!/^[A-Za-z]/.test(base)) base = `n_${base}`;
  let out = base;
  for (let i = 2; taken.has(out); i++) out = `${base}_${i}`;
  taken.add(out);
  return out;
}

function shape(n: DeployNode, text: string): string {
  const t = `"${esc(text)}"`;
  switch (n.kind) {
    case "traffic":
      return `[/${t}/]`;
    case "network":
      return `{{${t}}}`;
    case "compute":
      return `[[${t}]]`;
    case "cache":
      return `([${t}])`;
    case "database":
      return `[(${t})]`;
    case "messaging":
      return `>${t}]`;
    case "external":
      return `(${t})`;
    default:
      return `[${t}]`;
  }
}

function caption(n: DeployNode, catalog?: Catalog | null): string {
  const comp = catalog?.components.find((c) => c.type === n.node.type);
  const tech = technologyLabel(comp, n.cfg.technology);
  const label = n.node.label || n.node.id;
  const parts = [label];
  if (tech && tech !== "Generic" && !label.toLowerCase().includes(tech.toLowerCase())) parts.push(tech);
  if (n.kind === "compute") {
    const r = serviceReplicas(n.cfg);
    parts.push(n.cfg.platform === "serverless" ? "serverless" : n.cfg.autoscaling === true ? `${r}–${num(n.cfg.maxReplicas, r)} replicas` : `×${r}`);
  }
  if (n.kind === "database") {
    const shards = num(n.cfg.shards, 1);
    const reps = num(n.cfg.readReplicas, 0);
    if (shards > 1) parts.push(`${shards} shards`);
    if (reps > 0) parts.push(`+${reps} replicas`);
  }
  return parts.join(" · ");
}

export function toMermaid(doc: ArchitectureDocument, catalog?: Catalog | null): string {
  const nodes = deployNodes(doc, catalog);
  const taken = new Set<string>();
  const ids = new Map(nodes.map((n) => [n.node.id, mermaidId(n.node.id, taken)]));
  const lines = [`%% Generated by ArchSim from "${esc(doc.metadata.name)}". Review before publishing.`, "flowchart LR"];
  for (const n of nodes) lines.push(`  ${ids.get(n.node.id)}${shape(n, caption(n, catalog))}`);
  for (const e of doc.architecture.edges) {
    const a = ids.get(e.source);
    const b = ids.get(e.target);
    if (!a || !b) continue;
    const types = e.config.requestTypes ?? [];
    const label = e.sourcePort === "miss" ? "miss" : types.length === 1 ? `${types[0]}s` : "";
    const timeout = e.config.timeoutMs ? ` ${e.config.timeoutMs}ms` : "";
    const text = `${label}${timeout}`.trim();
    const arrow = e.sourcePort === "miss" ? "-.->" : "-->";
    lines.push(`  ${a} ${arrow}${text ? `|"${esc(text)}"|` : ""} ${b}`);
  }
  return `${lines.join("\n")}\n`;
}
