/**
 * Markdown decision report: what was designed, what was simulated, whether it meets the
 * objectives, what it costs, and what to look at. Meant to be pasted into a design doc or PR.
 */
import { formatUsd } from "./cost";
import { isDistribution, shortDistribution } from "./distributions";
import { errorBudget, evaluateSlo, formatSloValue } from "./slo";
import type { SweepAnalysis } from "./sweep";
import { technologyLabel } from "./theme";
import type { ArchitectureDocument, Catalog, CostEstimate, Distribution, Objectives, Report, Run } from "./types";

export interface ReviewItem {
  severity: string;
  title: string;
  detail?: string;
}

export interface DecisionReportInput {
  doc: ArchitectureDocument;
  catalog: Catalog | null;
  objectives: Objectives;
  run?: Run | null;
  report?: Report | null;
  review?: ReviewItem[];
  /** The engine's cost estimate of the design, used when there is no run. */
  designCost?: CostEstimate | null;
  sweep?: SweepAnalysis | null;
  generatedAt?: Date;
}

/** Escape text for a Markdown table cell. */
export function cell(v: unknown): string {
  return String(v ?? "").replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
}

function table(head: string[], rows: unknown[][]): string {
  const out = [`| ${head.map(cell).join(" | ")} |`, `| ${head.map(() => "---").join(" | ")} |`];
  for (const r of rows) out.push(`| ${r.map(cell).join(" | ")} |`);
  return out.join("\n");
}

const ms = (v: number | null | undefined) => (v == null ? "–" : v >= 1000 ? `${(v / 1000).toFixed(2)} s` : `${v >= 100 ? Math.round(v) : v.toFixed(1)} ms`);
const pct = (v: number | null | undefined, d = 2) => (v == null ? "–" : `${(v * 100).toFixed(d)}%`);
const rps = (v: number | null | undefined) => (v == null ? "–" : `${Math.round(v).toLocaleString("en-US")} req/s`);

function fieldValue(v: unknown, unit?: string): string {
  if (isDistribution(v)) return shortDistribution(v as Distribution, unit ?? "ms");
  if (typeof v === "number") return `${Number.isInteger(v) ? v.toLocaleString("en-US") : v.toFixed(2)}${unit ? ` ${unit}` : ""}`;
  if (typeof v === "boolean") return v ? "on" : "off";
  if (v == null) return "none";
  return String(v).replace(/_/g, " ");
}

/** Up to three headline settings of a node, e.g. "Replicas 2 · Workers per replica 4". */
function keySettings(type: string, config: Record<string, unknown>, catalog: Catalog | null): string {
  const comp = catalog?.components.find((c) => c.type === type);
  if (!comp) return "";
  return comp.fields
    .filter((f) => f.headline && f.key !== "technology")
    .slice(0, 3)
    .map((f) => `${f.label} ${fieldValue(config[f.key] ?? f.default, f.unit)}`)
    .join(" · ");
}

function patternText(doc: ArchitectureDocument): string {
  const w = doc.workload;
  const p = w.pattern;
  if (p.kind === "ramp") return `ramp ${rps(p.startRps)} → ${rps(p.endRps)}`;
  if (p.kind === "burst") return `${rps(w.rps)} with a burst to ${rps(p.burstRps)} at ${p.startS} s for ${p.durationS} s`;
  return `steady ${rps(w.rps)}`;
}

export function decisionReportMarkdown(input: DecisionReportInput): string {
  const { doc, catalog, objectives, run, report, review, sweep } = input;
  const generated = (input.generatedAt ?? new Date()).toISOString().replace(/\.\d+Z$/, "Z");
  const lines: string[] = [];
  const name = doc.metadata.name || "Untitled architecture";
  lines.push(`# ${name}: design decision report`, "");
  lines.push(
    `Generated by ArchSim on ${generated}. Results are estimates from a discrete-event simulation of the model and the assumptions below, not production measurements.`,
    "",
  );
  if (doc.metadata.description) lines.push(doc.metadata.description, "");

  // ---- verdict --------------------------------------------------------------------------
  const slo = report ? evaluateSlo(objectives, report) : null;
  // priced by the engine: the run's own estimate, else the design's
  const cost = report ? (report.cost ?? null) : (input.designCost ?? null);
  lines.push("## Summary", "");
  if (report && slo) {
    const verdict =
      slo.pass === true ? "Meets all objectives" : slo.pass === false ? `Misses ${slo.total - slo.met} of ${slo.total} objectives` : "No objectives set";
    const bottleneck = report.findings.find((f) => f.kind === "bottleneck");
    lines.push(`- **Verdict:** ${verdict}${run?.label ? ` (run "${run.label}")` : ""}.`);
    lines.push(`- **Throughput:** ${rps(report.summary.throughputRps)} of ${rps(report.summary.offeredRps)} offered; p95 ${ms(report.summary.latencyMs.p95)}; success ${pct(report.summary.successRate)}.`);
    if (bottleneck) lines.push(`- **Bottleneck:** ${bottleneck.title}.`);
  } else {
    lines.push("- No simulation run yet: run the design to evaluate it against the objectives.");
  }
  if (cost?.hasCost) {
    lines.push(
      `- **Estimated cost:** ${formatUsd(cost.monthly)} per month${cost.perMillionRequests != null ? `, ${formatUsd(cost.perMillionRequests)} per million successful requests` : ""}.`,
    );
  }
  if (sweep?.verdict && sweep.rows.length) lines.push(`- **Capacity:** ${sweep.verdict}`);
  lines.push("");

  // ---- design -----------------------------------------------------------------------------
  lines.push("## Design", "");
  const nodes = doc.architecture.nodes;
  lines.push(
    table(
      ["Component", "Type", "Technology", "Key settings"],
      nodes.map((n) => {
        const comp = catalog?.components.find((c) => c.type === n.type);
        const techValue = n.config?.technology ?? comp?.defaultConfig?.technology;
        const tech = techValue === "generic" ? null : technologyLabel(comp, techValue);
        return [n.label || n.id, comp?.displayName ?? n.type, tech ?? "–", keySettings(n.type, n.config ?? {}, catalog)];
      }),
    ),
    "",
  );
  lines.push(`${nodes.length} components and ${doc.architecture.edges.length} links.`, "");

  // ---- workload & objectives ----------------------------------------------------------------
  const w = doc.workload;
  lines.push("## Workload", "");
  lines.push(
    `- Traffic: ${patternText(doc)}, ${Math.round(w.readRatio * 100)}% reads / ${Math.round((1 - w.readRatio) * 100)}% writes, ${w.arrivalProcess} arrivals.`,
    `- Run: ${w.durationS} s with ${w.warmupS} s warm-up excluded, seed ${w.seed}.`,
  );
  const faults = w.faults ?? [];
  if (faults.length) {
    lines.push("- Faults injected:");
    for (const f of faults) {
      const what = f.kind === "outage" ? "outage" : f.kind === "slowdown" ? `slowdown ×${f.factor ?? 4}` : `+${f.extraMs ?? 200} ms latency`;
      lines.push(`  - ${f.label ? `${f.label}: ` : ""}${what} on \`${f.target}\` from ${f.startS} s for ${f.durationS} s`);
    }
  }
  lines.push("");
  lines.push("## Objectives", "");
  const objRows: string[][] = [];
  if (objectives.latencyP95Ms != null) objRows.push(["Latency p95", `≤ ${ms(objectives.latencyP95Ms)}`]);
  if (objectives.latencyP99Ms != null) objRows.push(["Latency p99", `≤ ${ms(objectives.latencyP99Ms)}`]);
  if (objectives.availability != null) objRows.push(["Availability", `≥ ${pct(objectives.availability, objectives.availability >= 0.999 ? 2 : 1)}`]);
  if (objectives.minThroughputRps != null) objRows.push(["Throughput", `≥ ${rps(objectives.minThroughputRps)}`]);
  lines.push(objRows.length ? table(["Objective", "Target"], objRows) : "No objectives set.", "");

  // ---- results ------------------------------------------------------------------------------
  if (report && slo) {
    lines.push("## Results", "");
    const p = report.provenance;
    lines.push(
      `Run${run?.label ? ` "${run.label}"` : ""}: seed ${p.seed}, engine ${p.engineVersion}, ${p.requestsGenerated.toLocaleString("en-US")} requests simulated, input digest \`${p.inputDigest.slice(0, 12)}\`, result digest \`${p.resultDigest.slice(0, 12)}\` (re-running the same input reproduces it exactly).`,
      "",
    );
    if (slo.checks.length) {
      lines.push(
        table(
          ["Objective", "Target", "Measured", "Result"],
          slo.checks.map((c) => [
            c.label,
            `${c.better === "lower" ? "≤" : "≥"} ${formatSloValue(c.key, c.target)}`,
            formatSloValue(c.key, c.actual),
            c.pass == null ? "no data" : c.pass ? "pass" : "**FAIL**",
          ]),
        ),
        "",
      );
    }
    const s = report.summary;
    lines.push(
      table(
        ["Metric", "Value"],
        [
          ["Offered load", rps(s.offeredRps)],
          ["Successful throughput", rps(s.throughputRps)],
          ["Success rate", pct(s.successRate)],
          ["Latency p50 / p95 / p99", `${ms(s.latencyMs.p50)} / ${ms(s.latencyMs.p95)} / ${ms(s.latencyMs.p99)}`],
          ["Timeouts", pct(s.timeoutRate)],
          ["Attempts per request", s.retryAmplification == null ? "–" : s.retryAmplification.toFixed(2)],
        ],
      ),
      "",
    );
    if ((s.clients?.length ?? 0) > 1) {
      lines.push(
        "By client:",
        "",
        table(
          ["Client", "Share", "Success rate", "Latency p50 / p95"],
          (s.clients ?? []).map((c) => [c.label, pct(c.share), pct(c.successRate), `${ms(c.latencyMs.p50)} / ${ms(c.latencyMs.p95)}`]),
        ),
        "",
      );
    }
    const budget = errorBudget(objectives, report);
    if (budget) {
      const used = budget.consumed == null ? "–" : Number.isFinite(budget.consumed) ? `${Math.round(budget.consumed * 100)}%` : "exhausted";
      lines.push(
        `Error budget: ${Math.round(budget.failed).toLocaleString("en-US")} failed requests against ${Math.round(budget.allowed).toLocaleString("en-US")} allowed by the availability objective (${used} used).`,
        "",
      );
    }
    const findings = report.findings.filter((f) => f.kind !== "healthy" || report.findings.length === 1);
    if (findings.length) {
      lines.push("### Findings", "");
      for (const f of findings) {
        lines.push(`- **${f.title}** (${f.severity}). ${f.detail}${f.suggestion ? ` Try: ${f.suggestion}` : ""}`);
      }
      lines.push("");
    }
  }

  // ---- capacity -----------------------------------------------------------------------------
  if (sweep && sweep.rows.length) {
    lines.push("## Breaking point", "", sweep.verdict, "");
    lines.push(
      table(
        ["Offered", "Throughput", "p95", "p99", "Success", "Bottleneck"],
        sweep.rows.map((r) => [rps(r.rps), rps(r.throughput), ms(r.p95), ms(r.p99), pct(r.successRate, 1), r.bottleneck ?? "–"]),
      ),
      "",
    );
  }

  // ---- cost ---------------------------------------------------------------------------------
  if (cost?.hasCost) {
    lines.push("## Cost estimate", "");
    lines.push(
      table(
        ["Component", "Basis", "Unit price", "Monthly"],
        cost.byNode.map((c) => [
          c.label,
          c.basis,
          c.unitPrice == null
            ? "not set"
            : c.unit === "hour"
              ? `${formatUsd(c.unitPrice)}/instance-hour${c.priceSource === "size" ? " (from size)" : ""}`
              : `${formatUsd(c.unitPrice)}/million calls`,
          formatUsd(c.monthly),
        ]),
      ),
      "",
      `Total ${formatUsd(cost.monthly)} per month (730 hours).${cost.perMillionRequests != null ? ` ${formatUsd(cost.perMillionRequests)} per million successful requests.` : ""}`,
      "",
    );
    for (const n of cost.notes) lines.push(`> ${n}`);
    if (cost.notes.length) lines.push("");
  }

  // ---- review -------------------------------------------------------------------------------
  if (review && review.length) {
    lines.push("## Design review", "");
    for (const r of review) lines.push(`- **${r.title}** (${r.severity})${r.detail ? `: ${r.detail}` : ""}`);
    lines.push("");
  }

  // ---- assumptions --------------------------------------------------------------------------
  lines.push("## Assumptions", "");
  const inputs = report?.assumptions.userInputs ?? [];
  lines.push(
    `Service times, hit ratios, latencies, prices and traffic are assumptions entered in the model${inputs.length ? ` (${inputs.length} values marked as assumptions)` : ""}. Calibrate them against real telemetry before treating absolute numbers as predictions; comparisons between options are more reliable than any single value.`,
    "",
  );
  return lines.join("\n");
}
