/** Typed client for the ArchSim v1 API (proxied same-origin under /api/v1). */
import type {
  Analysis,
  ArchitectureDocument,
  CalibrationRecord,
  Catalog,
  Comparison,
  ExampleSummary,
  Issue,
  Project,
  ProjectSummary,
  Report,
  Run,
} from "./types";
import { notifyUnauthorized, requestHeaders } from "./session";

export class ApiError extends Error {
  constructor(
    message: string,
    public status: number,
    public issues: Issue[] = [],
  ) {
    super(message);
    this.name = "ApiError";
  }
}

const BASE = "/api/v1";

/** One API call: JSON in and out, the current workspace attached; errors become ApiError. */
export async function request<T>(path: string, init?: RequestInit): Promise<T> {
  let res: Response;
  try {
    res = await fetch(`${BASE}${path}`, {
      ...init,
      headers: { "Content-Type": "application/json", ...requestHeaders(), ...(init?.headers ?? {}) },
      cache: "no-store",
    });
  } catch {
    throw new ApiError("Network error: cannot reach the ArchSim web server.", 0);
  }
  if (!res.ok) {
    if (res.status === 401 && !path.startsWith("/auth/")) notifyUnauthorized();
    let message = `${res.status} ${res.statusText}`;
    let issues: Issue[] = [];
    try {
      const body = await res.json();
      const detail = body?.detail;
      if (typeof detail === "string") message = detail;
      else if (detail?.message) {
        message = detail.message;
        issues = detail.issues ?? [];
      } else if (Array.isArray(detail)) {
        message = detail.map((d: { msg?: string }) => d.msg).join("; ");
      }
    } catch {
      /* non-JSON error body */
    }
    throw new ApiError(message, res.status, issues);
  }
  if (res.status === 204) return undefined as T;
  return (await res.json()) as T;
}

const json = (body: unknown) => JSON.stringify(body);

export const api = {
  components: () => request<Catalog>("/components"),
  examples: () => request<ExampleSummary[]>("/examples"),
  example: (id: string) => request<ArchitectureDocument>(`/examples/${encodeURIComponent(id)}`),
  /** Set inputs from telemetry (Prometheus or OpenTelemetry) and replay; returns a new document. */
  calibrate: (body: CalibrateRequest) => request<CalibrateResult>("/calibrate", { method: "POST", body: json(body) }),
  /** A design from a docker-compose file, Kubernetes manifests or a Terraform plan, with the import report. */
  importDesign: (body: { format: ImportFormat; text: string; name?: string | null }) =>
    request<ImportResult>("/import", { method: "POST", body: json(body) }),
  /** Price sources a design can name: generic and the snapshots on the API's machine. */
  pricing: () => request<{ sources: PricingSource[] }>("/pricing"),
  /** docker-compose, Kubernetes or Mermaid scaffolding of a design, generated by the engine. */
  exportDesign: (document: ArchitectureDocument, format: "compose" | "k8s" | "mermaid") =>
    request<{ format: string; text: string; suffix: string; mediaType: string }>("/export", {
      method: "POST",
      body: json({ document, format }),
    }),
  /** Auto sizes, cost estimate and design review, computed by the engine (no simulation). */
  analyze: (document: ArchitectureDocument, scenarioId?: string | null) =>
    request<Analysis>("/analyze", { method: "POST", body: json({ document, scenarioId: scenarioId ?? null }) }),
  validate: (document: ArchitectureDocument, scenarioId?: string | null) =>
    request<{ valid: boolean; issues: Issue[] }>("/validate", {
      method: "POST",
      body: json({ document, scenarioId: scenarioId ?? null }),
    }),

  listProjects: () => request<ProjectSummary[]>("/projects"),
  createProject: (body: {
    name?: string;
    description?: string;
    document?: ArchitectureDocument;
    exampleId?: string;
    /** With exampleId and no name: reopen the copy made last time if it was never saved. */
    reuseUnedited?: boolean;
  }) => request<Project>("/projects", { method: "POST", body: json(body) }),
  importProject: (document: unknown) =>
    request<Project>("/projects/import", { method: "POST", body: json(document) }),
  getProject: (id: string) => request<Project>(`/projects/${id}`),
  updateProject: (
    id: string,
    body: { name?: string; description?: string; document?: ArchitectureDocument; expectedRevision?: number },
  ) => request<Project>(`/projects/${id}`, { method: "PUT", body: json(body) }),
  deleteProject: (id: string) => request<void>(`/projects/${id}`, { method: "DELETE" }),
  duplicateProject: (id: string) => request<Project>(`/projects/${id}/duplicate`, { method: "POST" }),

  createRun: (
    projectId: string,
    body: { scenarioId?: string | null; label?: string; document?: ArchitectureDocument },
  ) => request<Run>(`/projects/${projectId}/runs`, { method: "POST", body: json(body) }),
  batchRuns: (projectId: string, scenarioIds: (string | null)[], document?: ArchitectureDocument) =>
    request<Run[]>(`/projects/${projectId}/runs/batch`, {
      method: "POST",
      body: json({ scenarioIds, document }),
    }),
  listRuns: (projectId: string) => request<Run[]>(`/projects/${projectId}/runs`),
  getRun: (id: string) => request<Run>(`/runs/${id}`),
  getReport: (id: string) => request<Report>(`/runs/${id}/report`),
  cancelRun: (id: string) => request<Run>(`/runs/${id}/cancel`, { method: "POST" }),
  rerun: (id: string) => request<Run>(`/runs/${id}/rerun`, { method: "POST" }),
  deleteRun: (id: string) => request<void>(`/runs/${id}`, { method: "DELETE" }),
  compare: (a: string, b: string) =>
    request<Comparison>(`/compare?a=${encodeURIComponent(a)}&b=${encodeURIComponent(b)}`),
};

export type ImportFormat = "compose" | "k8s" | "terraform";

/** What an import mapped, guessed (marked assumed), ignored and suggests linking. */
export interface ImportReport {
  source: string;
  mapped: string[];
  guessed: string[];
  ignored: string[];
  suggestions: { source: string; target: string; reason: string }[];
  issues: Issue[];
}

export interface ImportResult {
  document: ArchitectureDocument;
  report: ImportReport;
}

export interface PricingSource {
  provider: string;
  region: string | null;
  date: string | null;
  illustrative: boolean;
  note?: string | null;
  /** Hash of the snapshot's content. */
  sha256?: string;
  /** The newest snapshot of its provider and region (older ones are listed for pinned designs). */
  newest?: boolean;
}

export interface CalibrateRequest {
  document: ArchitectureDocument;
  source: "prometheus" | "otlp";
  mapping?: string | null;
  prometheusUrl?: string | null;
  recorded?: Record<string, unknown> | null;
  range?: string | null;
  traces?: Record<string, unknown> | null;
}

export interface CalibrateResult {
  document: ArchitectureDocument;
  changes: { path: string; label: string; before: unknown; after: unknown; fitError: number | null; query: string | null }[];
  notes: string[];
  calibration: CalibrationRecord | null;
  /** "This model reproduces the observed p95 … within N%; the largest of M replay errors is …",
   * when a replay ran. */
  summary: string | null;
}
