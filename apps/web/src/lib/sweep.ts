/**
 * Breaking-point finder: step the offered load across short runs and read the curve.
 *
 * The knee is the first step where the system stops keeping up (successful throughput below 95%
 * of the offered load) or tail latency jumps (p95 at least 4x the lightest step's and 2x the
 * previous step's, so gradual growth does not count). The useful
 * capacity number is the highest load that still meets every objective, which is usually below
 * raw saturation.
 */
import { tooManyFailures } from "./slo";
import type { ArchitectureDocument, Objectives, Override, Report, Scenario } from "./types";

export const SWEEP_SCENARIO_PREFIX = "sweep-";
/** The server accepts at most 10 scenarios per batch. */
export const MAX_SWEEP_STEPS = 10;

export interface SweepConfig {
  fromRps: number;
  toRps: number;
  steps: number;
  /** Arrival window per step (s). */
  durationS: number;
  /** Excluded from each step's statistics (s). */
  warmupS: number;
}

export interface SweepRow {
  /** Target offered load of the step (req/s). */
  rps: number;
  runId: string | null;
  offered: number | null;
  throughput: number | null;
  p50: number | null;
  p95: number | null;
  p99: number | null;
  /** p95 counting each failed request as a full client timeout (null in reports before 1.12). */
  p95WithFailures: number | null;
  successRate: number | null;
  errorRate: number | null;
  /** Label of the primary bottleneck reported for the step, if any. */
  bottleneck: string | null;
}

export interface SweepAnalysis {
  rows: SweepRow[];
  /** First step where the system stops keeping up; null if it never does in range. */
  knee: SweepRow | null;
  kneeReason: "throughput" | "latency" | null;
  /** Highest load that meets every objective (contiguously from the lightest step). */
  maxWithinSlo: SweepRow | null;
  /** Bottleneck at the knee (or at the heaviest step when there is no knee). */
  saturatedAt: string | null;
  /**
   * First step at which more requests failed than the objectives allow. From there on the
   * latency percentiles (successful requests only) no longer describe the load.
   */
  failingFrom: SweepRow | null;
  verdict: string;
}

function niceStep(raw: number): number {
  if (raw <= 0) return 1;
  const mag = 10 ** Math.floor(Math.log10(raw));
  const r = raw / mag;
  const nice = r <= 1 ? 1 : r <= 2 ? 2 : r <= 2.5 ? 2.5 : r <= 5 ? 5 : 10;
  return nice * mag;
}

/** A sensible default range around the current baseline load. */
export function suggestRange(currentRps: number): { fromRps: number; toRps: number } {
  const base = currentRps > 0 ? currentRps : 100;
  const step = niceStep(base / 4);
  const fromRps = Math.max(step, Math.round((base * 0.5) / step) * step);
  const toRps = Math.max(fromRps + step, Math.round((base * 3) / step) * step);
  return { fromRps, toRps };
}

/** Evenly spaced, rounded load levels from `fromRps` to `toRps` (inclusive), unique and ascending. */
export function sweepLevels(cfg: Pick<SweepConfig, "fromRps" | "toRps" | "steps">): number[] {
  const steps = Math.max(2, Math.min(MAX_SWEEP_STEPS, Math.round(cfg.steps)));
  const lo = Math.max(0.1, Math.min(cfg.fromRps, cfg.toRps));
  const hi = Math.max(cfg.fromRps, cfg.toRps);
  const out: number[] = [];
  for (let i = 0; i < steps; i++) {
    const v = lo + ((hi - lo) * i) / (steps - 1);
    const rounded = v >= 100 ? Math.round(v / 5) * 5 : v >= 10 ? Math.round(v) : Math.round(v * 10) / 10;
    if (!out.includes(rounded)) out.push(rounded);
  }
  return out;
}

function safeIdPart(v: number): string {
  return String(v).replace(/[^0-9]/g, "_");
}

/**
 * A copy of `doc` with one generated scenario per load level. Each step runs a constant load at
 * the level for a short window and drops any faults, so the curve measures steady-state capacity.
 * The scenarios exist only in this transient document; the saved design is not changed.
 */
export function buildSweepDocument(
  doc: ArchitectureDocument,
  cfg: SweepConfig,
): { document: ArchitectureDocument; scenarioIds: string[]; levels: number[] } {
  const levels = sweepLevels(cfg);
  const durationS = Math.max(2, cfg.durationS);
  const warmupS = Math.max(0, Math.min(cfg.warmupS, durationS - 1));
  const taken = new Set(doc.scenarios.map((s) => s.id));
  const stamp = Date.now().toString(36).slice(-5);
  const generated: Scenario[] = levels.map((rps, i) => {
    let id = `${SWEEP_SCENARIO_PREFIX}${stamp}-${i + 1}-${safeIdPart(rps)}`.slice(0, 64);
    while (taken.has(id)) id = `${id.slice(0, 60)}-${Math.floor(Math.random() * 1000)}`;
    taken.add(id);
    const w = (path: string, value: unknown): Override => ({ target: { kind: "workload" }, path, value });
    return {
      id,
      name: `Breaking point · ${rps.toLocaleString("en-US")} req/s`,
      description: "Generated by the breaking-point finder (constant load, short run, no faults).",
      overrides: [w("pattern", { kind: "constant" }), w("rps", rps), w("durationS", durationS), w("warmupS", warmupS), w("faults", [])],
    };
  });
  // The document may hold at most 50 scenarios; generated ones take priority in this copy.
  const keep = doc.scenarios.filter((s) => !s.id.startsWith(SWEEP_SCENARIO_PREFIX)).slice(0, 50 - generated.length);
  return {
    document: { ...doc, scenarios: [...keep, ...generated] },
    scenarioIds: generated.map((s) => s.id),
    levels,
  };
}

/** Requests per second that failed at a step (null while unknown). */
export function failedRps(row: Pick<SweepRow, "offered" | "successRate">): number | null {
  return row.offered != null && row.successRate != null ? row.offered * (1 - row.successRate) : null;
}

/** One curve row from a step's report. */
export function sweepRow(rps: number, report: Report | null, runId: string | null = null): SweepRow {
  if (!report) {
    return { rps, runId, offered: null, throughput: null, p50: null, p95: null, p99: null, p95WithFailures: null, successRate: null, errorRate: null, bottleneck: null };
  }
  const s = report.summary;
  const bottleneck = report.findings.find((f) => f.kind === "bottleneck");
  const label = bottleneck?.nodeId ? (report.nodes.find((n) => n.id === bottleneck.nodeId)?.label ?? null) : null;
  const errorRate = s.successRate != null ? 1 - s.successRate : null;
  return {
    rps,
    runId,
    offered: s.offeredRps,
    throughput: s.throughputRps,
    p50: s.latencyMs.p50,
    p95: s.latencyMs.p95,
    p99: s.latencyMs.p99,
    p95WithFailures: s.latencyWithFailuresMs?.p95 ?? null,
    successRate: s.successRate,
    errorRate,
    bottleneck: label,
  };
}

/** Does a step meet the objectives that make sense per step (latency and availability)? */
export function rowMeetsSlo(row: SweepRow, obj: Objectives): boolean | null {
  if (row.throughput == null) return null;
  if (obj.latencyP95Ms != null && (row.p95 == null || row.p95 > obj.latencyP95Ms)) return false;
  if (obj.latencyP99Ms != null && (row.p99 == null || row.p99 > obj.latencyP99Ms)) return false;
  if (obj.availability != null && (row.successRate == null || row.successRate < obj.availability)) return false;
  return true;
}

const fmt = (v: number) => Math.round(v).toLocaleString("en-US");

export function analyzeSweep(input: SweepRow[], obj: Objectives): SweepAnalysis {
  const rows = input.filter((r) => r.throughput != null).sort((a, b) => a.rps - b.rps);
  if (rows.length === 0) {
    return { rows, knee: null, kneeReason: null, maxWithinSlo: null, saturatedAt: null, failingFrom: null, verdict: "No completed steps yet." };
  }
  const baseP95 = rows.find((r) => r.p95 != null)?.p95 ?? null;
  let knee: SweepRow | null = null;
  let kneeReason: SweepAnalysis["kneeReason"] = null;
  for (let i = 0; i < rows.length; i++) {
    const r = rows[i];
    const offered = r.offered ?? r.rps;
    if (offered > 0 && (r.throughput ?? 0) < 0.95 * offered) {
      knee = r;
      kneeReason = "throughput";
      break;
    }
    const prev = i > 0 ? rows[i - 1].p95 : null;
    if (baseP95 != null && prev != null && r.p95 != null && r.p95 >= 4 * baseP95 && r.p95 >= 2 * prev && r.p95 - baseP95 >= 5) {
      knee = r;
      kneeReason = "latency";
      break;
    }
  }
  let maxWithinSlo: SweepRow | null = null;
  for (const r of rows) {
    if (rowMeetsSlo(r, obj) === true) maxWithinSlo = r;
    else break;
  }
  const saturatedAt = (knee ?? rows[rows.length - 1]).bottleneck;
  const first = rows[0];
  const last = rows[rows.length - 1];
  let verdict: string;
  if (!maxWithinSlo) {
    verdict = `Misses the objectives already at ${fmt(first.rps)} req/s, the lightest step.`;
  } else if (maxWithinSlo === last && !knee) {
    verdict = `Holds ${fmt(last.rps)} req/s within the objectives with no sign of saturation. Try a higher range to find the limit.`;
  } else {
    verdict = `Holds ${fmt(maxWithinSlo.rps)} req/s within the objectives`;
    if (knee) verdict += `; ${kneeReason === "latency" ? "latency climbs sharply" : "saturates"} around ${fmt(knee.rps)} req/s`;
    if (saturatedAt) verdict += ` at ${saturatedAt}`;
    verdict += ".";
  }
  const failingFrom = rows.find((r) => tooManyFailures(r.successRate, obj)) ?? null;
  return { rows, knee, kneeReason, maxWithinSlo, saturatedAt, failingFrom, verdict };
}
