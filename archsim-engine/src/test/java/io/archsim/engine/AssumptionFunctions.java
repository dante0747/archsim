package io.archsim.engine;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.function.Function;

import tools.jackson.databind.JsonNode;
import tools.jackson.databind.node.ArrayNode;

import io.archsim.engine.assumptions.AssumptionsPage;
import io.archsim.engine.assumptions.EngineConstant;
import io.archsim.engine.assumptions.EngineConstants;
import io.archsim.model.component.standard.StandardComponents;
import io.archsim.parity.GoldenEntry;
import io.archsim.parity.GoldenFile;

/**
 * The page of every number ArchSim uses without the user typing it, and the engine-wide
 * constants it lists.
 */
final class AssumptionFunctions {

	// ENGINE_VERSION and REPORT_VERSION are not checked: the Java engine is 1.0.0 and
	// writes report 1.15 (ADR-0050), departures the engine's README lists
	static final Map<String, Function<GoldenEntry, JsonNode>> PORTED = Map.ofEntries(
			Map.entry("archsim_engine.assumptions.constants", (entry) -> constants()),
			Map.entry("archsim_engine.assumptions.render", (entry) -> GoldenJson.text(asTheFrozenEngineWroteIt(
					AssumptionsPage.render(StandardComponents.registry(), recordingEngine(entry))))));

	/**
	 * The page's two lines that name the command that writes it, the Java's to the
	 * Python's: the Gradle task writes the page since the Python script was deleted with
	 * the frozen engine.
	 */
	private static final Map<String, String> GENERATOR_LINES = Map.of(
			"<!-- Generated by ./gradlew :archsim-engine:generate from the engine; do not edit by hand. -->",
			"<!-- Generated by scripts/gen_assumptions.py from the engine; do not edit by hand. -->",
			"Generated from the code that uses these values (`./gradlew :archsim-engine:generate`); a test fails "
					+ "when this file is out of date.",
			"Generated from the code that uses these values (`uv run python scripts/gen_assumptions.py`); a test "
					+ "fails when this file is out of date.");

	/**
	 * The page's line on a third-party API's default price per million calls, the Java's
	 * to the Python's: schema 1.9 leaves the price unset where it defaulted to 0
	 * (ADR-0081).
	 */
	private static final Map<String, String> API_PRICE_LINES = Map.of(
			"|  | Cost per million calls (`costPerMillionRequests`) | none |",
			"|  | Cost per million calls (`costPerMillionRequests`) | 0 $ |");

	/**
	 * The presets that no longer set a price per call (ADR-0081), whose price of 0 Python
	 * listed after their last setting: each preset's first row on the page, and that
	 * setting.
	 */
	private static final Map<String, String> UNPRICED_PRESETS = Map.of("| Payments API |",
			"|  | Rate limit (`rateLimitRps`) | 100 req/s | illustrative |", "| Identity provider |",
			"|  | Rate limit (`rateLimitRps`) | 200 req/s | illustrative |");

	/**
	 * The code of the Kafka broker's measured sizes, which the frozen engine did not have
	 * (ADR-0085): its constants and their rows are left out.
	 */
	private static final String KAFKA_CODE = "sizing.KAFKA_";

	/** Those constants' code on the page, in code font. */
	private static final String KAFKA_CODE_ON_THE_PAGE = "`" + KAFKA_CODE;

	/**
	 * The code of the default sibling speed of a part's vCPUs, which the frozen engine
	 * did not have (ADR-0091): its constant and its row are left out.
	 */
	private static final String VCPU_CODE = "vcpus.";

	/** That constant's code on the page, in code font. */
	private static final String VCPU_CODE_ON_THE_PAGE = "`" + VCPU_CODE;

	/**
	 * The page's section on the instance families whose vCPUs are whole cores, its last,
	 * which the frozen engine's page did not have (ADR-0091).
	 */
	private static final String WHOLE_CORE_FAMILIES = "## Instance families whose vCPUs are whole cores";

	/**
	 * The legend's line on a measured basis, which the frozen engine's page did not have.
	 */
	private static final String MEASURED_BASIS = "- **measured**:";

	/** The price per call those presets set, as Python listed it. */
	private static final String PRESET_PRICE = "|  | Cost per million calls (`costPerMillionRequests`) | 0 $ "
			+ "| illustrative |";

	private AssumptionFunctions() {
	}

	/**
	 * A page as the frozen engine rendered it, which named its own script.
	 * @param page the page the Java engine renders
	 * @return the page with the lines that name the Gradle task replaced by the frozen
	 * engine's, which named its script, and its lines on an API's price by the frozen
	 * engine's: its default, and the payments and identity presets'
	 * @throws IllegalStateException when the page lacks one of those lines
	 */
	private static String asTheFrozenEngineWroteIt(String page) {
		List<String> lines = new ArrayList<>(page.lines().toList());
		Map<String, String> replaced = new HashMap<>(GENERATOR_LINES);
		replaced.putAll(API_PRICE_LINES);
		replaced.forEach((java, python) -> {
			int line = lines.indexOf(java);
			if (line < 0) {
				throw new IllegalStateException("the page no longer has the line: " + java);
			}
			lines.set(line, python);
		});
		UNPRICED_PRESETS.forEach((preset, last) -> lines.add(lastSetting(lines, preset, last) + 1, PRESET_PRICE));
		lines.removeIf((line) -> line.contains(KAFKA_CODE_ON_THE_PAGE) || line.contains(VCPU_CODE_ON_THE_PAGE)
				|| line.startsWith(MEASURED_BASIS));
		int families = lines.indexOf(WHOLE_CORE_FAMILIES);
		if (families < 0) {
			throw new IllegalStateException("the page no longer has the section: " + WHOLE_CORE_FAMILIES);
		}
		// the page's last section, and the blank line before it
		lines.subList(families - 1, lines.size()).clear();
		return String.join("\n", lines) + "\n";
	}

	// a preset's last setting on the page
	private static int lastSetting(List<String> lines, String preset, String last) {
		int first = lines.stream()
			.filter((line) -> line.startsWith(preset))
			.findFirst()
			.map(lines::indexOf)
			.orElseThrow(() -> new IllegalStateException("the page no longer lists the preset " + preset));
		int setting = lines.subList(first, lines.size()).indexOf(last);
		if (setting < 0) {
			throw new IllegalStateException("the preset " + preset + " no longer lists " + last);
		}
		return first + setting;
	}

	/**
	 * The version of the engine that recorded an entry, which the page it rendered names.
	 * @param entry a golden entry
	 * @return the version its golden file records
	 */
	private static String recordingEngine(GoldenEntry entry) {
		return GoldenFile.read(entry.file()).root().required("engineVersion").stringValue();
	}

	/**
	 * The constants as the Python's {@code Constant} dataclasses are recorded.
	 * @return the constants, in the page's order
	 */
	private static ArrayNode constants() {
		ArrayNode out = GoldenJson.NODES.arrayNode();
		for (EngineConstant constant : EngineConstants.all()) {
			if (constant.code().startsWith(KAFKA_CODE) || constant.code().startsWith(VCPU_CODE)) {
				continue;
			}
			out.addObject()
				.put("area", constant.area())
				.put("name", constant.name())
				.put("value", constant.value())
				.put("code", constant.code())
				.put("source", constant.source());
		}
		return out;
	}

}
