package io.archsim.engine.export;

import java.util.List;

import org.junit.jupiter.api.Test;
import tools.jackson.databind.json.JsonMapper;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * YAML text as the exports write it: block style, each scalar plain unless YAML would
 * read it as something else.
 */
class YamlTextTests {

	private static final JsonMapper JSON = JsonMapper.builder().build();

	@Test
	void write_plainText_isUnquoted() {
		String text = YamlText.write(JSON.readTree("{\"image\": \"postgres:16\", \"path\": \"/var/lib/data\"}"));

		assertThat(text).isEqualTo("image: postgres:16\npath: /var/lib/data");
	}

	@Test
	void write_wordYamlReadsAsABoolean_isQuoted() {
		String text = YamlText.write(JSON.readTree("{\"Yes\": \"off\"}"));

		assertThat(text).isEqualTo("\"Yes\": \"off\"");
	}

	@Test
	void write_textWithAColonAndSpace_isQuoted() {
		String text = YamlText.write(JSON.readTree("[\"a: b\", \"edge:\", \"8080:80\"]"));

		assertThat(text).isEqualTo("- \"a: b\"\n- \"edge:\"\n- \"8080:80\"");
	}

	@Test
	void write_textEndingInOneNewline_staysPlainAsThePythonEngineWroteIt() {
		String text = YamlText.write(JSON.readTree("{\"label\": \"ok\\n\"}"));

		assertThat(text).isEqualTo("label: ok\n");
	}

	@Test
	void write_numbers_areWholeWithoutAPointBelowTenToTheTwentyOneElseTheirRepr() {
		String text = YamlText.write(JSON.readTree("[2.0, 0.5, -0.0, 1e-05, 1e21, 12345678901234567890123, 7]"));

		assertThat(text).isEqualTo("- 2\n- 0.5\n- 0\n- 1e-05\n- 1e+21\n- 1.2345678901234568e+22\n- 7");
	}

	@Test
	void write_mapInAList_startsOnTheDashLine() {
		String text = YamlText.write(JSON.readTree("[{\"name\": \"main\", \"port\": 80}]"));

		assertThat(text).isEqualTo("- name: main\n  port: 80");
	}

	@Test
	void write_listInAList_startsBelowItsDash() {
		String text = YamlText.write(JSON.readTree("[[1, [true, null]]]"));

		assertThat(text).isEqualTo("-\n  - 1\n  -\n    - true\n    - null");
	}

	@Test
	void write_emptyCollections_areWrittenInline() {
		String text = YamlText.write(JSON.readTree("{\"volumes\": {}, \"ports\": [], \"items\": [[], {}]}"));

		assertThat(text).isEqualTo("volumes: {}\nports: []\nitems:\n  - []\n  - {}");
	}

	@Test
	void comments_lines_areEachACommentAndAnEmptyOneAHashAlone() {
		String text = YamlText.comments(List.of("Generated by ArchSim.", "", "Review it."));

		assertThat(text).isEqualTo("# Generated by ArchSim.\n#\n# Review it.");
	}

}
