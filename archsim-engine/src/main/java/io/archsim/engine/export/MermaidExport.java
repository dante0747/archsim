package io.archsim.engine.export;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.HashSet;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Optional;
import java.util.Set;
import java.util.regex.Pattern;

import io.archsim.engine.load.ComponentFamily;
import io.archsim.engine.technology.TechnologyNames;
import io.archsim.model.component.ComponentRegistry;
import io.archsim.model.document.ArchitectureDocument;
import io.archsim.model.document.EdgeConfig;
import io.archsim.model.document.EdgeSpec;

/**
 * A Mermaid flowchart of a design: each part it deploys in the shape of its kind, named
 * with its technology and its replicas or shards, and each link between them with the
 * requests it carries and its timeout.
 */
public final class MermaidExport {

	/** The port a cache's misses leave from. */
	private static final String MISS = "miss";

	private static final Pattern NOT_AN_ID = Pattern.compile("[^A-Za-z0-9_]");

	private static final Pattern STARTS_WITH_A_LETTER = Pattern.compile("^[A-Za-z].*", Pattern.DOTALL);

	private final DeployParts parts;

	private final TechnologyNames names;

	/**
	 * Draws designs made of a registry's types.
	 * @param registry the component types
	 */
	public MermaidExport(ComponentRegistry registry) {
		this.parts = new DeployParts(registry);
		this.names = new TechnologyNames(registry);
	}

	/**
	 * The design as a Mermaid flowchart.
	 * @param document the design, with the specs it is to be deployed with
	 * @return the chart's text, ending in a newline
	 */
	public String write(ArchitectureDocument document) {
		List<DeployPart> deployed = this.parts.of(document);
		Set<String> taken = new HashSet<>();
		Map<String, String> ids = new HashMap<>();
		deployed.forEach((part) -> ids.put(part.id(), mermaidId(part.id(), taken)));
		List<String> lines = new ArrayList<>();
		lines.add("%% Generated by ArchSim from \"" + escaped(document.metadata().name())
				+ "\". Review before publishing.");
		lines.add("flowchart LR");
		deployed.forEach((part) -> lines.add("  " + ids.get(part.id()) + shape(part.family(), caption(part))));
		for (EdgeSpec link : document.architecture().edges()) {
			String from = ids.get(link.source());
			String to = ids.get(link.target());
			if (from != null && to != null) {
				lines.add(arrow(link, from, to));
			}
		}
		return String.join("\n", lines) + "\n";
	}

	private static String arrow(EdgeSpec link, String from, String to) {
		EdgeConfig config = link.config();
		boolean miss = link.sourcePort().equals(MISS);
		String carries = "";
		if (miss) {
			carries = MISS;
		}
		else if (config.requestTypes().size() == 1) {
			carries = config.requestTypes().getFirst().json() + "s";
		}
		String timeout = (config.timeoutMs() != null) ? " " + YamlText.number(config.timeoutMs()) + "ms" : "";
		String text = (carries + timeout).strip();
		String label = text.isEmpty() ? "" : "|" + quoted(text) + "|";
		return "  " + from + " " + (miss ? "-.->" : "-->") + label + " " + to;
	}

	/**
	 * A part's caption: its name, its technology unless its name says it, and its
	 * replicas or shards. The names are compared in lower case as the JDK's Unicode
	 * lowers them.
	 * @param part the part
	 * @return its caption
	 */
	private String caption(DeployPart part) {
		String label = part.node().name();
		List<String> words = new ArrayList<>(List.of(label));
		technologyName(part).filter((name) -> !name.equals("Generic"))
			.filter((name) -> !label.toLowerCase(Locale.ROOT).contains(name.toLowerCase(Locale.ROOT)))
			.ifPresent(words::add);
		if (part.family() == ComponentFamily.COMPUTE) {
			words.add(replicas(part));
		}
		if (part.family() == ComponentFamily.DATABASE) {
			double shards = part.number("shards", 1);
			double readReplicas = part.number("readReplicas", 0);
			if (shards > 1) {
				words.add(YamlText.number(shards) + " shards");
			}
			if (readReplicas > 0) {
				words.add("+" + YamlText.number(readReplicas) + " replicas");
			}
		}
		return String.join(" · ", words);
	}

	private Optional<String> technologyName(DeployPart part) {
		return part.settings()
			.text("technology")
			.flatMap((technology) -> this.names.of(part.node().type(), technology));
	}

	private static String replicas(DeployPart service) {
		double replicas = service.replicas();
		if (service.settings().is("platform", "serverless")) {
			return "serverless";
		}
		if (service.settings().isTrue("autoscaling")) {
			return YamlText.number(replicas) + "–" + YamlText.number(service.number("maxReplicas", replicas))
					+ " replicas";
		}
		return "×" + YamlText.number(replicas);
	}

	private static String shape(ComponentFamily family, String caption) {
		String shape = switch (family) {
			case TRAFFIC -> "[/%s/]";
			case NETWORK -> "{{%s}}";
			case COMPUTE -> "[[%s]]";
			case CACHE -> "([%s])";
			case DATABASE -> "[(%s)]";
			case MESSAGING -> ">%s]";
			case EXTERNAL -> "(%s)";
			case OTHER -> "[%s]";
		};
		return shape.formatted(quoted(caption));
	}

	/**
	 * A part's id as a Mermaid id, unlike any taken before it.
	 * @param id the part's id
	 * @param taken the Mermaid ids taken, to which this one is added
	 * @return letters, digits and underscores, starting with a letter
	 */
	private static String mermaidId(String id, Set<String> taken) {
		String base = NOT_AN_ID.matcher(id).replaceAll("_");
		if (!STARTS_WITH_A_LETTER.matcher(base).matches()) {
			base = "n_" + base;
		}
		String mermaidId = base;
		for (int next = 2; taken.contains(mermaidId); next++) {
			mermaidId = base + "_" + next;
		}
		taken.add(mermaidId);
		return mermaidId;
	}

	private static String quoted(String text) {
		return "\"" + escaped(text) + "\"";
	}

	private static String escaped(String text) {
		return text.replace("\"", "#quot;");
	}

}
