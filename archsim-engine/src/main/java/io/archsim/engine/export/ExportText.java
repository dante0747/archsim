package io.archsim.engine.export;

import java.math.BigDecimal;
import java.util.List;
import java.util.Locale;
import java.util.regex.Pattern;
import java.util.stream.Collectors;

import io.archsim.engine.text.HalfUp;
import io.archsim.model.catalog.ComponentCatalog;

/**
 * The names and words the exports share: DNS names, whole numbers, the header that says
 * what an export is, and the note on experimental technologies.
 */
final class ExportText {

	/** The longest DNS label. */
	private static final int DNS_LABEL_LENGTH = 63;

	/** A fraction times this is a percentage. */
	private static final double PERCENT = 100;

	/** The longest name a design's slug keeps. */
	private static final int SLUG_LENGTH = 40;

	private static final Pattern NOT_DNS = Pattern.compile("[^a-z0-9-]+");

	private static final Pattern EDGE_DASHES = Pattern.compile("^-+|-+$");

	private static final Pattern NOT_ENVIRONMENT = Pattern.compile("[^A-Z0-9]+");

	private ExportText() {
	}

	/**
	 * An id as a DNS name: lower case letters, digits and dashes, at most 63 of them.
	 * @param id the id
	 * @return the name; {@code node} when nothing is left
	 */
	static String dnsName(String id) {
		String name = EDGE_DASHES.matcher(NOT_DNS.matcher(id.toLowerCase(Locale.ROOT)).replaceAll("-")).replaceAll("");
		name = name.substring(0, Math.min(name.length(), DNS_LABEL_LENGTH));
		return name.isEmpty() ? "node" : name;
	}

	/**
	 * A design's name as the name of its compose project and its Kubernetes parts.
	 * @param name the design's name
	 * @return its DNS name, at most 40 characters; that of {@code architecture} for an
	 * empty name
	 */
	static String slug(String name) {
		String slug = dnsName(name.isEmpty() ? "architecture" : name);
		return slug.substring(0, Math.min(slug.length(), SLUG_LENGTH));
	}

	/**
	 * A compose service name as the start of an environment variable's name.
	 * @param name the service's name
	 * @return the name in capitals, each run of other characters an underscore
	 */
	static String environmentName(String name) {
		return NOT_ENVIRONMENT.matcher(name.toUpperCase(Locale.ROOT)).replaceAll("_");
	}

	/**
	 * What a queue's partitions and consumers are, for a reader of the export.
	 * @param queue the queue
	 * @return {@code 12 partitions, 3 consumers}
	 */
	static String messaging(DeployPart queue) {
		return YamlText.number(queue.number("partitions", 1)) + " partitions, "
				+ YamlText.number(queue.number("consumers", 1)) + " consumers";
	}

	/**
	 * A whole number, all its digits.
	 * @param value the number, whole
	 * @return its digits
	 */
	static String whole(double value) {
		return new BigDecimal(value).toBigInteger().toString();
	}

	/**
	 * A number rounded as JavaScript's {@code Math.round}, halves up.
	 * @param value the number
	 * @return the whole number nearest it, all its digits
	 */
	static String rounded(double value) {
		return whole(HalfUp.javaScriptRound(value));
	}

	/**
	 * A fraction as a whole percentage, rounded as JavaScript's {@code Math.round}.
	 * @param fraction the fraction
	 * @return the percentage, a whole number
	 */
	static double percent(double fraction) {
		return HalfUp.javaScriptRound(fraction * PERCENT);
	}

	/**
	 * What every export starts with: where it comes from, and that it is scaffolding.
	 * @param name the design's name
	 * @param what what the export is
	 * @return its lines
	 */
	static List<String> header(String name, String what) {
		return List.of("Generated by ArchSim from \"" + name + "\": " + what + ".",
				"Starting-point scaffolding, not a production config. Review images, versions, credentials,",
				"resources, probes and storage before using it. Capacity values come from the model's assumptions;",
				"CPU, memory and storage come from each part's resource specs where you set them.");
	}

	/**
	 * The note on the parts whose technology is experimental.
	 * @param parts the parts deployed
	 * @return one line naming them, with what experimental means; none when there are
	 * none
	 */
	static List<String> tierLines(List<DeployPart> parts) {
		List<DeployPart> experimental = parts.stream().filter(DeployPart::experimental).toList();
		if (experimental.isEmpty()) {
			return List.of();
		}
		String named = experimental.stream()
			.map((part) -> part.node().name() + ": " + part.settings().text("technology").orElse(""))
			.collect(Collectors.joining(", "));
		return List.of("Experimental technologies (" + named + "): " + ComponentCatalog.TIER_NOTE);
	}

}
