package io.archsim.engine.assumptions;

import java.util.ArrayList;
import java.util.Collection;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;

import tools.jackson.databind.JsonNode;

import io.archsim.model.catalog.ComponentCatalog;
import io.archsim.model.component.ComponentRegistry;
import io.archsim.model.component.Tier;

/**
 * {@code docs/assumptions.md}: every number ArchSim uses without the user typing it, and
 * where each comes from. It reads the values from the code that uses them: the technology
 * profiles, presets and part defaults of the component types (through the catalog the
 * editor reads), and the engine-wide constants ({@link EngineConstants}). Each value is
 * marked documented (with the link that states it) or illustrative.
 */
public final class AssumptionsPage {

	private static final String SETTING = "Setting";

	private static final String VALUE = "Value";

	private static final String BASIS = "Basis";

	private AssumptionsPage() {
	}

	/**
	 * The page, which names the engine whose numbers it lists.
	 * @param registry the component types, without plugins
	 * @param engineVersion that engine's version: {@code EngineVersions.ENGINE} for this
	 * one
	 * @return the page's Markdown, ending with one newline
	 */
	public static String render(ComponentRegistry registry, String engineVersion) {
		JsonNode catalog = ComponentCatalog.of(registry);
		List<CatalogPart> parts = CatalogPart.all(registry, catalog);
		Map<String, JsonNode> edgeFields = PageText.byKey(catalog.path("edgeFields"));
		List<String> lines = new ArrayList<>(intro(engineVersion));
		lines.addAll(tiers(parts));
		lines.addAll(profiles(parts));
		lines.addAll(presets(parts, edgeFields));
		lines.addAll(partDefaults(parts, edgeFields, PageText.byKey(catalog.path("workloadFields"))));
		lines.addAll(constants());
		return String.join("\n", lines).replaceFirst("\n+$", "") + "\n";
	}

	private static List<String> intro(String engineVersion) {
		return List.of("# Assumptions", "",
				"<!-- Generated by scripts/gen_assumptions.py from the engine; do not edit by hand. -->", "",
				"Every number ArchSim " + engineVersion + " uses without you typing it, and where it comes from:", "",
				"- **documented**: the vendor's documentation states it (linked);",
				"- **illustrative**: a typical value ArchSim chose, not a vendor guarantee and not a measurement. "
						+ "Replace it with your own numbers before trusting absolute results.",
				"", "Generated from the code that uses these values (`uv run python scripts/gen_assumptions.py`); a "
						+ "test fails when this file is out of date.",
				"");
	}

	private static List<String> tiers(List<CatalogPart> parts) {
		List<List<String>> rows = new ArrayList<>();
		for (CatalogPart part : withProfiles(parts)) {
			rows.add(List.of(part.displayName(), PageText.technologies(part.technologies(), Tier.CORE),
					PageText.technologies(part.technologies(), Tier.EXPERIMENTAL)));
		}
		List<String> lines = new ArrayList<>(List.of("## Technology tiers", "",
				"**Core** technologies are the ones ArchSim focuses on and will validate against measurements first. "
						+ "**Experimental** ones stay available, with a badge in the parts library, the inspector, "
						+ "reports and exports that says: \"" + ComponentCatalog.TIER_NOTE + "\" The generic part of "
						+ "each kind is core: it adds no technology behaviour, only the shared mechanisms (workers, "
						+ "connections, queues, service times) that the core technologies use too. No technology has "
						+ "been validated against measurements yet.",
				""));
		lines.addAll(PageText.table(List.of("Part", "Core", "Experimental"), rows));
		lines.add("");
		return lines;
	}

	private static List<String> profiles(List<CatalogPart> parts) {
		List<String> lines = new ArrayList<>(List.of("## Technology behaviour defaults", "",
				"What each technology sets for its \"auto\" settings (Technology behaviour in the inspector). "
						+ "Setting one on a part overrides it.",
				""));
		for (CatalogPart part : withProfiles(parts)) {
			List<List<String>> rows = profileRows(part);
			if (!rows.isEmpty()) {
				lines.addAll(section(part.displayName(), List.of("Technology", SETTING, VALUE, BASIS), rows));
			}
		}
		return lines;
	}

	private static List<List<String>> profileRows(CatalogPart part) {
		Map<String, JsonNode> fields = part.fields();
		List<List<String>> rows = new ArrayList<>();
		part.technologies().forEach((technology, profile) -> {
			boolean first = true;
			for (String key : profile.values().keySet()) {
				String name = first ? "`" + technology + "`, " + profile.tier().json() : "";
				rows.add(List.of(name, PageText.label(fields, key),
						PageText.value(part.technologyDefault(key, technology), PageText.unit(fields, key)),
						PageText.basis(part.technologySource(key, technology))));
				first = false;
			}
		});
		return rows;
	}

	private static List<String> presets(List<CatalogPart> parts, Map<String, JsonNode> edgeFields) {
		List<String> lines = new ArrayList<>(List.of("## Preset numbers", "",
				"The numbers a technology preset fills in when you add it from the parts library. Prices are "
						+ "illustrative until real cloud prices are added.",
				""));
		for (CatalogPart part : parts) {
			if (!part.presets().isEmpty()) {
				lines.addAll(section(part.displayName(), List.of("Preset", SETTING, VALUE, BASIS), presetRows(part)));
			}
		}
		List<List<String>> links = new ArrayList<>();
		for (CatalogPart part : parts) {
			part.linkDefaults()
				.properties()
				.forEach((link) -> links
					.add(List.of(part.displayName(), "Link " + PageText.label(edgeFields, link.getKey()),
							PageText.value(link.getValue(), "ms"), PageText.basis(null))));
		}
		if (!links.isEmpty()) {
			lines.addAll(section("Links drawn from client parts", List.of("Client", SETTING, VALUE, BASIS), links));
		}
		return lines;
	}

	private static List<List<String>> presetRows(CatalogPart part) {
		Map<String, JsonNode> fields = part.fields();
		List<List<String>> rows = new ArrayList<>();
		for (JsonNode preset : part.presets()) {
			JsonNode tier = preset.path("tier");
			String title = preset.path("name").stringValue() + (tier.isString() ? ", " + tier.stringValue() : "");
			boolean first = true;
			for (Map.Entry<String, JsonNode> setting : preset.path("config").properties()) {
				String key = setting.getKey();
				if (!"technology".equals(key)) {
					JsonNode source = preset.path("sources").path(key);
					rows.add(List.of(first ? title : "", PageText.label(fields, key),
							PageText.value(setting.getValue(), PageText.unit(fields, key)),
							PageText.basis(source.isString() ? source.stringValue() : null)));
					first = false;
				}
			}
		}
		return rows;
	}

	/**
	 * The defaults of a new part, link and workload: the settings marked as assumptions.
	 * @param parts the component types
	 * @param edgeFields the link settings' descriptions, by name
	 * @param workloadFields the workload settings' descriptions, by name
	 * @return the section's lines
	 */
	private static List<String> partDefaults(List<CatalogPart> parts, Map<String, JsonNode> edgeFields,
			Map<String, JsonNode> workloadFields) {
		List<List<String>> rows = new ArrayList<>();
		for (CatalogPart part : parts) {
			Set<String> byTechnology = new HashSet<>();
			part.technologies().values().forEach((profile) -> byTechnology.addAll(profile.values().keySet()));
			rows.addAll(defaultRows(part.displayName(), part.fields().values(), byTechnology));
		}
		rows.addAll(defaultRows("Link", edgeFields.values(), Set.of()));
		rows.addAll(defaultRows("Workload", workloadFields.values(), Set.of()));
		List<String> lines = new ArrayList<>(List.of("## Defaults of a new part", "",
				"Settings marked as assumptions (≈ in the inspector) are numbers you assert about your system. "
						+ "A new part starts with these illustrative defaults; replace them with your own "
						+ "measurements. Every run lists the values it used under Assumptions.",
				""));
		lines.addAll(PageText.table(List.of("Part", SETTING, "Default"), rows));
		lines.add("");
		return lines;
	}

	/**
	 * The defaults rows of one part, the link or the workload: its settings marked as
	 * assumptions, each with its default.
	 * @param title the part's name, on its first row
	 * @param fields its settings' descriptions
	 * @param byTechnology the settings a technology fills in when they are empty
	 * @return the rows
	 */
	private static List<List<String>> defaultRows(String title, Collection<JsonNode> fields, Set<String> byTechnology) {
		List<List<String>> rows = new ArrayList<>();
		for (JsonNode field : fields) {
			if (field.path("assumption").booleanValue()) {
				String key = field.path("key").stringValue();
				JsonNode value = field.path("default");
				String shown = (value.isNull() && byTechnology.contains(key)) ? "the technology's default (above)"
						: PageText.value(value, PageText.unitOf(field));
				rows.add(List.of(rows.isEmpty() ? title : "", PageText.labelOf(field), shown));
			}
		}
		return rows;
	}

	private static List<String> constants() {
		List<List<String>> rows = EngineConstants.all()
			.stream()
			.map((constant) -> List.of(constant.area(), constant.name(), constant.value(),
					PageText.basis(constant.source()), "`" + constant.code() + "`"))
			.toList();
		List<String> lines = new ArrayList<>(List.of("## Engine constants", "",
				"Numbers built into the sizing, cost and component models. Design review thresholds (for example 80% "
						+ "CPU at the peak) are rules of thumb stated with each finding, not inputs to the simulation.",
				""));
		lines.addAll(PageText.table(List.of("Area", "Constant", VALUE, BASIS, "Code"), rows));
		lines.add("");
		return lines;
	}

	private static List<String> section(String title, List<String> head, List<List<String>> rows) {
		List<String> lines = new ArrayList<>(List.of("### " + title, ""));
		lines.addAll(PageText.table(head, rows));
		lines.add("");
		return lines;
	}

	private static List<CatalogPart> withProfiles(List<CatalogPart> parts) {
		return parts.stream().filter((part) -> !part.technologies().isEmpty()).toList();
	}

}
