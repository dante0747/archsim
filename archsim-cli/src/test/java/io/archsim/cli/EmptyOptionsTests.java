package io.archsim.cli;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.stream.Stream;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * An option that names a file to write, given empty ({@code -o ""}), is not given: the
 * Python CLI tested such options by their truth ({@code if args.out:}), so it printed
 * what it would have written, and wrote no report.
 */
class EmptyOptionsTests {

	private static final String COMPOSE = """
			services:
			  api:
			    image: nginx
			""";

	@TempDir
	private Path folder;

	@Test
	void run_emptyOut_writesNoReport() throws IOException {
		Path design = SmallDesign.write(this.folder, SmallDesign.WORKLOAD);

		ArchsimRun run = ArchsimRun.of("run", design.toString(), "--out", "");

		assertThat(run.exitCode()).isZero();
		assertThat(run.out()).doesNotContain("report written");
		assertThat(filesInFolder()).containsExactly(design);
	}

	@Test
	void import_emptyOut_printsTheDesign() throws IOException {
		Path compose = writeCompose();

		ArchsimRun run = ArchsimRun.of("import", "compose", compose.toString(), "-o", "");

		assertThat(run.exitCode()).isZero();
		assertThat(run.out()).startsWith("{");
		assertThat(run.err()).doesNotContain("wrote");
	}

	@Test
	void import_emptyReport_writesNoReport() throws IOException {
		Path compose = writeCompose();
		Path design = this.folder.resolve("design.json");

		ArchsimRun run = ArchsimRun.of("import", "compose", compose.toString(), "-o", design.toString(), "--report",
				"");

		assertThat(run.exitCode()).isZero();
		assertThat(filesInFolder()).containsExactlyInAnyOrder(compose, design);
	}

	@Test
	void export_emptyOut_printsTheExport() throws IOException {
		Path design = SmallDesign.write(this.folder, SmallDesign.WORKLOAD);

		ArchsimRun run = ArchsimRun.of("export", "compose", design.toString(), "-o", "");

		assertThat(run.exitCode()).isZero();
		assertThat(run.out()).startsWith("# Generated by ArchSim").contains("services:");
		assertThat(run.err()).doesNotContain("wrote");
	}

	private Path writeCompose() throws IOException {
		return Files.writeString(this.folder.resolve("compose.yaml"), COMPOSE);
	}

	private List<Path> filesInFolder() throws IOException {
		try (Stream<Path> files = Files.list(this.folder)) {
			return files.toList();
		}
	}

}
